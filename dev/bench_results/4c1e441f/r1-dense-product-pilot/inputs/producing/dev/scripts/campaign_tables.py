#!/usr/bin/env python3
"""Shared result tables of a lane-comparison family's committed campaigns.

A family supplies its title, its stages, its ledger and its receipt pin; the
stage sections, the lane-witness table, the ledger table, the direction-agreement
table and the source digests are the same for every such family and live here.
Import it as

    sys.path.insert(0, os.path.join(root, "dev/scripts"))
    import campaign_tables

and call `campaign_tables.main(...)` from the family's own generator.

Every row is read from a committed acceptance summary, receipt, ledger line or
receipt pin at run time; the generator carries no figure of its own and no clock
reading, so two consecutive runs over the same committed bytes produce the same
file. A stage that is not committed yet is reported as absent rather than
guessed.
"""

import hashlib
import json
import os


def digest(path):
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def table(rows, header):
    widths = [max(len(str(row[i])) for row in [header] + rows) for i in range(len(header))]
    lines = ["| " + " | ".join(str(h).ljust(w) for h, w in zip(header, widths)) + " |",
             "|" + "|".join("-" * (w + 2) for w in widths) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(v).ljust(w) for v, w in zip(row, widths)) + " |")
    return lines


def lanes(receipt):
    """Distinct selected paths each cell's two arms reported, with counts."""
    observed = {}
    for cell in receipt["cells"]:
        for pair in cell.get("pairs") or []:
            for role in ("baseline", "candidate"):
                execution = pair[role]
                key = (cell["cell_id"], role, execution["arm"], execution["selected_path"])
                observed[key] = observed.get(key, 0) + 1
    return observed


def stage_sections(root, label, directory, lines):
    summary_path = os.path.join(root, directory, "acceptance-summary.json")
    receipt_path = os.path.join(root, directory, "receipt.json")
    lines.append(f"## {label.capitalize()}")
    lines.append("")
    if not os.path.isfile(summary_path):
        lines += [f"No committed {label} receipt at `{directory}`.", ""]
        return None
    with open(summary_path) as handle:
        summary = json.load(handle)
    with open(receipt_path) as handle:
        receipt = json.load(handle)
    family = summary["family"]
    lines += [
        f"Campaign `{summary['campaign_id']}`, verdict `{summary['verdict']}`, "
        f"qualifies `{summary['qualifies']}`.",
        "",
    ]
    lines += table(
        [[family["family_id"], family["comparisons"], family["family_alpha"],
          family.get("attempt_alpha", ""), family.get("corrected_alpha", ""),
          family["per_comparison_confidence"]]],
        ["family", "comparisons", "family alpha", "attempt alpha", "corrected alpha",
         "per-comparison confidence"])
    lines.append("")
    rows = []
    for cell in summary["cells"]:
        interval = cell.get("interval") or {}
        rows.append([
            cell["cell_id"], cell["outcome"], cell.get("pairs", ""),
            interval.get("estimate", ""), interval.get("lower", ""), interval.get("upper", ""),
            cell.get("flagged_windows", ""), cell.get("total_windows", ""),
        ])
    lines += table(rows, ["cell", "outcome", "pairs", "estimate", "lower", "upper",
                          "flagged windows", "total windows"])
    lines += ["", f"### {label.capitalize()} lane witness", "",
              "The path each arm reported after its timed windows, as the receipt records it.",
              ""]
    lines += table(
        [[cell_id, role, arm, path, count]
         for (cell_id, role, arm, path), count in sorted(lanes(receipt).items())],
        ["cell", "position", "arm", "selected path", "executions"])
    lines.append("")
    return summary


def main(root, output, title, generator, stages, ledger, pin_path, agreement_heading,
         agreement_note):
    """Writes the family's tables.

    `stages` is an ordered list of `(label, receipt directory)` pairs.
    `agreement_note` is the family's own paragraph about what the pinned receipt
    is cited for, as a list of lines.
    """
    lines = [
        f"# {title}",
        "",
        f"Generated by `{generator}` from the committed receipts,",
        "acceptance summaries, family ledger and receipt pin named on the Source lines below.",
        "",
    ]
    summaries = {}
    for label, directory in stages:
        summaries[label] = stage_sections(root, label, directory, lines)

    lines += ["## Family ledger", ""]
    entries = [json.loads(line) for line in open(os.path.join(root, ledger)) if line.strip()]
    if entries:
        lines += table(
            [[entry["sequence"], entry["family"], entry["campaign"], entry["protocol_version"],
              entry["comparisons"], entry["addendum_sha256"][:16]] for entry in entries],
            ["sequence", "family", "campaign", "protocol", "comparisons", "addendum sha256"])
    else:
        lines.append("The genesis ledger is open and holds no reservation.")
    lines.append("")

    lines += [f"## {agreement_heading}", ""]
    with open(os.path.join(root, pin_path)) as handle:
        pin = json.load(handle)
    lines += [
        f"Pinned receipt `{pin['receipt']}`, sha256 `{pin['receipt_sha256']}`, "
        f"family `{pin['family_id']}`, verdict `{pin['verdict']}`.",
        "",
    ]
    lines += list(agreement_note)
    lines.append("")
    prior_summary = os.path.join(root, os.path.dirname(pin["acceptance_summary"]),
                                 "acceptance-summary.json")
    with open(prior_summary) as handle:
        prior = json.load(handle)
    prior_cells = {cell["cell_id"]: cell for cell in prior["cells"]}
    here = summaries.get("confirmation")
    if here is None:
        lines += ["No committed confirmation receipt, so no direction is stated yet.", ""]
    else:
        rows = []
        for cell in here["cells"]:
            other = prior_cells.get(cell["cell_id"])
            mine = (cell.get("interval") or {}).get("estimate")
            theirs = (other or {}).get("interval", {}).get("estimate")
            if other is None or mine is None or theirs is None:
                agreement = "no matching pinned cell"
            elif (mine > 1.0) == (theirs > 1.0):
                agreement = "agrees"
            else:
                agreement = "disagrees"
            rows.append([cell["cell_id"], mine if mine is not None else "",
                         theirs if theirs is not None else "", agreement])
        lines += table(rows, ["cell", "this family estimate", "pinned estimate", "direction"])
        lines.append("")

    lines += ["## Source", ""]
    sources = [ledger, pin_path, pin["receipt"], pin["acceptance_summary"]]
    for _, directory in stages:
        for name in ("receipt.json", "acceptance-summary.json"):
            candidate = f"{directory}/{name}"
            if os.path.isfile(os.path.join(root, candidate)):
                sources.append(candidate)
    lines += table([[path, digest(os.path.join(root, path))] for path in sources],
                   ["path", "sha256"])

    with open(output, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"{output}: {len(lines)} lines")
