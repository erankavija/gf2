#!/usr/bin/env bash
# Record the gf2x build evidence REQ-02 requires (jit:c7113c5a).
#
# Usage:
#   ./record-build-evidence.sh [output-file] [staging-directory]
#
# Reads the source export and the three build trees `fetch-build.sh` produced
# and emits: the source pin and license condition, the autotools that generated
# the build system, and for each variant the configure-resolved compiler,
# CFLAGS, build compiler and hwdir, the basecase headers configure linked in,
# the algorithm thresholds and the algorithm gf2x_mul_r selects at every
# measured operand size, the library digest, and the carry-less-multiply
# instruction census with the symbols that carry it. Every line is extracted
# from the source or build tree at run time; nothing here is transcribed.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(git -C "${HERE}" rev-parse --show-toplevel)"
ISSUE=c7113c5a
OUT="${1:-${HERE}/gf2x-build-evidence-v3.txt}"
EXT="${2:-${GF2_SURVEY_EXT:-${REPO}/target/${ISSUE}-ext}}"
LIB=lib/libgf2x.so.3.0.0
SIZES="4 9 64 256 2048"

pin() { sed -n "s/^${1}=\"\(.*\)\"$/\1/p" "${HERE}/fetch-build.sh"; }

# The algorithm gf2x_mul_r selects for balanced n-word operands, derived from
# the installed thresholds header with the selection logic of gf2x.c and
# toom.c (cited in source-evidence.json).
selection() {
    python3 - "$1" ${SIZES} <<'PY'
import re, sys
text = open(sys.argv[1]).read()
def define(name):
    return int(re.search(r"#define\s+%s\s+(\d+)" % name, text).group(1))
def table(name):
    body = re.search(r"#define\s+%s\s*(\{.*?\})\s*\n\s*(?:#|/\*|$)" % name, text, re.S).group(1)
    return [int(v) for v in re.findall(r"-?\d+", body)]
kara = define("GF2X_MUL_KARA_THRESHOLD")
limit = define("GF2X_TOOM_TUNING_LIMIT")
best = table("GF2X_BEST_TOOM_TABLE")
fft = table("GF2X_MUL_FFT_TABLE")
fft = list(zip(fft[0::2], fft[1::2]))
names = {0: "gf2x_mul_kara", 1: "gf2x_mul_tc3", 2: "gf2x_mul_tc3w", 3: "gf2x_mul_tc4"}
for n in map(int, sys.argv[2:]):
    if n < kara:
        print(f"    {n:>5} words  basecase gf2x_mul{n} (n < GF2X_MUL_KARA_THRESHOLD {kara})")
        continue
    k = [kk for size, kk in fft if size <= n][-1]
    if k not in (0, 1):
        print(f"    {n:>5} words  gf2x_mul_fft K={k}")
        continue
    code = 3 if n > limit or best[n - 1] < 0 else best[n - 1]
    print(f"    {n:>5} words  {names[code]} (FFT table K={k}; GF2X_BEST_TOOM_TABLE[{n - 1}] = {best[n - 1]})")
PY
}

emit() {
    echo "# gf2x build evidence (jit:${ISSUE})"
    echo "# generated by dev/active/${ISSUE}/survey/record-build-evidence.sh"
    echo
    echo "source"
    echo "  url          $(pin GF2X_URL)"
    echo "  tag          $(pin GF2X_TAG) (fetch-build.sh verifies it resolves to the commit)"
    echo "  commit       $(cat "${EXT}/gf2x/.source-commit") (exported with git archive)"
    echo "  toom-gpl.c   $(stat -c %s "${EXT}/gf2x/toom-gpl.c") bytes; contains \"released under the GPL\": $(grep -c 'released under the GPL' "${EXT}/gf2x/toom-gpl.c") line(s)"
    echo "  license      $(pin GF2X_LICENSE) when configure.ac defines GPL_CODE_PRESENT"
    echo
    echo "generated build system (autoreconf -i on the export)"
    echo "  $(grep -m1 -o 'Generated by GNU Autoconf [0-9.]*' "${EXT}/gf2x/configure")"
    echo "  $(grep -m1 -o 'generated by automake [0-9.]*' "${EXT}/gf2x/Makefile.in")"
    echo "  $(grep -m1 -o '^VERSION=.*' "${EXT}/gf2x/config/ltmain.sh" | sed 's/^/libtool ltmain.sh /')"
    echo
    echo "build host"
    echo "  cc           $(gcc --version | head -1)"
    echo "  cpu          $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ //')"
    echo
    for name in conservative tuned native; do
        local_dir="${EXT}/build-${name}"
        prefix="${EXT}/prefix-${name}"
        echo "variant ${name}"
        echo "  configure invocation"
        sed -n 's/^  \$ \(.*configure .*\)$/    \1/p' "${local_dir}/config.log" | head -1
        sed -n 's/^configure: *//p' "${local_dir}/configure.stdout.log" \
            | grep -E '^(using ABI|CC=|CFLAGS=|CPPFLAGS=|hwdir=)' | sed 's/^/  /'
        echo "  CC_FOR_BUILD=$(sed -n "s/^CC_FOR_BUILD='\(.*\)'$/\1/p" "${local_dir}/config.log")"
        echo "  GPL_CODE_PRESENT $(sed -n 's/^#define GPL_CODE_PRESENT \([01]\).*/\1/p' "${local_dir}/gf2x/gf2x-config.h" "${local_dir}/config.h" 2>/dev/null | head -1)"
        echo "  selected basecase headers (config.status link records)"
        grep -o 'already_tuned/[a-z0-9_]*/[a-z0-9_.-]*\.h' "${local_dir}/configure.stdout.log" \
            | sort -u | sed 's/^/    /'
        echo "  algorithm thresholds (installed gf2x-thresholds.h, sizes in 64-bit words)"
        sed -n 's/^#define[[:space:]]*\(GF2X_MUL_[A-Z0-9_]*THRESHOLD\)[[:space:]]*\([0-9]*\).*/    \1 \2/p' \
            "${prefix}/include/gf2x/gf2x-thresholds.h"
        echo "  gf2x_mul_r selection for the measured balanced operand sizes"
        selection "${prefix}/include/gf2x/gf2x-thresholds.h"
        echo "  library      ${prefix}/${LIB}"
        echo "  sha256       $(sha256sum "${prefix}/${LIB}" | cut -d' ' -f1)"
        echo "  size         $(stat -c %s "${prefix}/${LIB}") bytes"
        echo "  carry-less multiply instruction census (objdump -d)"
        objdump -d "${prefix}/${LIB}" \
            | awk '{for (i = 1; i <= NF; i++) if ($i ~ /^v?pclmul/) { print $i; break }}' \
            | sort | uniq -c | sed 's/^/    /'
        echo "  ymm-operand carry-less multiplies (256-bit VPCLMULQDQ)"
        echo "    $(objdump -d "${prefix}/${LIB}" | grep -E 'v?pclmul' | grep -c ymm || true)"
        echo "  symbols carrying carry-less multiplies"
        objdump -d "${prefix}/${LIB}" \
            | awk '/^[0-9a-f]+ </ { symbol = $2 } /v?pclmul/ { count[symbol]++ } END { for (s in count) print count[s], s }' \
            | sort -k1,1rn -k2 | sed 's/^/    /'
        echo
    done
    echo "measured entry point"
    echo "  gf2x_mul_r(c, a, an, b, bn, pool): unreduced product of two"
    echo "  polynomials over GF(2), operands spanning an and bn unsigned longs,"
    echo "  product an+bn words, little-endian words with bit i of word j the"
    echo "  coefficient of x^(64j+i)."
    nm -D --defined-only "${EXT}/prefix-native/${LIB}" | grep -E ' T gf2x_mul(_r|_pool_(init|clear))?$' | sed 's/^/  /'
}

emit >"${OUT}"
echo "wrote ${OUT}" >&2
