    lines = ["# Carry-less crossover and polynomial competitiveness evidence tables", ""]
    lines += PREAMBLE

    family_section(
        lines,
        "Family `gf2m-clmul-crossover`",
        CROSSOVER_CONFIRMATION,
        [
            ("Resolution pilot", CROSSOVER_PILOT_R2),
            ("Exploratory pilot", CROSSOVER_PILOT),
            ("Wire smoke", CROSSOVER_SMOKE),
        ],
    )
    family_section(
        lines,
        "Family `wide-polynomial-competitiveness`",
        POLYNOMIAL_CONFIRMATION,
        [("Exploratory pilot", POLYNOMIAL_PILOT)],
    )

    lines += ["## Measurement resolution", ""]
    resolution_rows(lines)

    lines += ["## Frozen margins and declared resolution", ""]
    declared_effects(lines)

    lines += ["## Holdout declaration", ""]
    holdout(lines)

    lines += ["## Family ledger chains", ""]
    ledger_chains(lines)

    lines += ["## Arm executables", ""]
    executables(lines)

