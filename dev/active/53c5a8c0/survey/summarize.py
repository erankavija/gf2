#!/usr/bin/env python3
"""Project this issue's committed receipts into evidence tables.

Usage: dev/active/53c5a8c0/survey/summarize.py

Reads only committed receipts, acceptance summaries, receipt-local input
snapshots, frozen addenda, the committed ledgers, the holdout declaration, the
resolution derivation records and the validation record, and writes
`dev/bench_results/53c5a8c0/tables.md`. Every number in the output is recomputed
or projected from those files; nothing is transcribed by hand.

Speedups, intervals, decisions and outcomes come from the acceptance summaries
that `benchmark-acceptance` recomputes from the raw pairs. The reciprocal
columns are algebraic transformations of the same estimate and endpoints and add
no samples. Per-arm call times, window counts, selected paths and conversion
diagnostics are descriptive summaries of the per-execution values in
`receipt.json`; they carry no interval and decide nothing.

The two families keep separate sections throughout, because a raw independent
carry-less batch, a reduced element-wise batch, a GF(2^m) dot product, an
unreduced long polynomial product and a whole-consumer wide-field product are
distinct operations and no table averages across them.
"""

