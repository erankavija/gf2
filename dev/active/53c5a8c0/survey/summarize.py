def asm_bodies(lines):
    """Instruction-mix rows of the committed assembly artefacts."""
    lines += [
        "Source: the committed artefacts under `dev/active/53c5a8c0/survey/asm/`, whose "
        "derived annotation blocks `dev/active/53c5a8c0/survey/annotate-asm.py` counts from "
        "the disassembly above each block. The rows below are read back out of those "
        "blocks, so this table adds no count of its own.",
        "",
    ]
    wanted = ("instructions", "stack frame bytes", "frame stores", "frame loads",
              "backward branches")
    rows = []
    for name in sorted(os.listdir(os.path.join(ACTIVE, "survey", "asm"))):
        path = os.path.join(ACTIVE, "survey", "asm", name)
        body = None
        counted = {}
        clmul = 0
        for line in open(path, encoding="utf-8"):
            if line.startswith(";=== derived annotation for "):
                if body:
                    rows.append(_asm_row(name, body, counted, clmul, wanted))
                body = line[len(";=== derived annotation for "):].rstrip(" =\n")
                counted, clmul = {}, 0
            elif body and line.startswith("; "):
                text = line[2:].rstrip("\n")
                label, _, value = text.rpartition("  ")
                label, value = label.strip(), value.strip()
                if not value.isdigit():
                    continue
                if label in wanted:
                    counted[label] = value
                if "carry-less multiply" in label:
                    clmul += int(value)
        if body:
            rows.append(_asm_row(name, body, counted, clmul, wanted))
    table(lines, ["Artefact", "Body", "Instructions", "Stack frame bytes",
                  "Frame stores", "Frame loads", "Backward branches",
                  "Carry-less multiply instructions"], rows)


def _asm_row(artefact, body, counted, clmul, wanted):
    return (
        ["`{}`".format(artefact), "`{}`".format(body)]
        + [counted.get(label, "0") for label in wanted]
        + [str(clmul)]
    )


def write(path, lines):
    text = "\n".join(lines).rstrip("\n") + "\n"
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)


def family_section(lines, title, confirmation, pilots):
    lines += ["## {}".format(title), "", "### Confirmation", ""]
    summary, receipt = cell_decisions(lines, confirmation)
    lines += ["#### Findings", ""]
    findings(lines, summary)
    lines += ["#### Family accounting and P-20 tail support", ""]
    family_accounting(lines, confirmation, summary, receipt)
    lines += ["#### Per-arm call time and selected path", ""]
    arm_medians(lines, receipt)
    lines += ["#### Untimed conversion diagnostics", ""]
    diagnostics(lines, receipt)
    lines += ["#### Sessions and host", ""]
    sessions(lines, confirmation, receipt)
    for label, directory in pilots:
        lines += ["### {}".format(label), ""]
        _, pilot_receipt = cell_decisions(lines, directory)
        lines += ["#### Per-arm call time and selected path", ""]
        arm_medians(lines, pilot_receipt)
        lines += ["#### Untimed conversion diagnostics", ""]
        diagnostics(lines, pilot_receipt)


