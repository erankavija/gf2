#!/usr/bin/env python3
"""Outcome tables of the inter-frame LDPC decoder (jit:7211ae53).

Writes one Markdown file from the committed evidence of the story's results directory, the
directory OUT lies in: the campaign each family ledger there names last, with its acceptance
summary, receipt, plan and execution log; the peak-memory record there; the decoder calibration
campaign; and the profile series whose summary names a profiling executable of the story's arms.
Every campaign's execution log is verified before anything is rendered, by
`verify-campaign-log.py`, by the calibration's `verify-campaign.py` and by the profile
summarizer's `verified_sessions`; a campaign that does not verify stops the run and nothing is
written.

Cells are parted by their addendum's `decoder.arm_kind` (PARTS), so matched-algorithm and
fastest-compatible results never share a table. An arm's time per call is the median of the
receipt's per-execution `ns_per_call` with the order-statistic interval of the profile
summarizer's `median_interval`, and its throughput is frames per call over that time.

Usage (from the worktree root): make-outcome-tables.py OUT
"""

import functools
import importlib.util
import json
import pathlib
import re
import sys
from collections import defaultdict

sys.dont_write_bytecode = True


def load(path):
    module = importlib.util.module_from_spec(importlib.util.spec_from_file_location(
        path.stem.replace("-", "_"), path))
    module.__spec__.loader.exec_module(module)
    return module


SURVEY = pathlib.Path(__file__).resolve().parent
outcome = load(SURVEY / "make-collection-outcome.py")
smoke, generator = outcome.smoke, outcome.generator
verifier = outcome.load(smoke.ROOT / smoke.located("file", "verify-campaign-log.py"))
CALIBRATION = SURVEY.parent / "calibration"
TITLE = "# Outcome tables of the inter-frame LDPC decoder"
PARTS = {
    "matched-algorithm": "Matched-algorithm results",
    "fastest-quality-compatible": "Fastest-compatible results",
}
SINGLE_CORE = "single-core"
EXTERNAL = "external"
DECODER_REPORT = "batch-decoder-diagnostics"
# Arm environment entries that locate inputs rather than select behaviour.
INPUT_ENVIRONMENT = ("GF2_LDPC_QUALITY",)
GENERATED_BY = re.compile(r"Generated by `([^`]+)`")


def read(path):
    return json.loads(path.read_bytes())


def link(place, target, text=None):
    return f"[{text or f'`{generator.repository_path(target)}`'}]({outcome.link(place, target)})"


@functools.cache
def summarizer(summary_path):
    """The profile summarizer the summary's Markdown projection names as its generator."""
    projection = (summary_path.parent / "profile.md").read_text(encoding="utf-8")
    return outcome.load(smoke.ROOT / GENERATED_BY.search(projection).group(1))


@functools.cache
def profile_summary():
    """The one committed profile summary whose series profiled an executable of the story's arms."""
    arms = generator.repository_path(SURVEY / "arms").as_posix() + "/"
    found = [smoke.ROOT / path for path in smoke.listed("profile-summary.json")
             if read(smoke.ROOT / path)["resolution"]["executable"].startswith(arms)]
    if len(found) != 1:
        sys.exit(f"{len(found)} profile summaries profile the story's arms; exactly one must")
    return found[0]


def median_interval(values):
    return summarizer(profile_summary()).median_interval(values)


def outcome_directories(results):
    """The receipt directory of the campaign each family ledger under `results` names last."""
    ledgers = sorted(smoke.ROOT / path for path in smoke.listed("ledger.jsonl")
                     if (smoke.ROOT / path).is_relative_to(results)
                     and "inputs" not in pathlib.Path(path).parts)
    last = [json.loads(ledger.read_text(encoding="utf-8").splitlines()[-1])["campaign"]
            for ledger in ledgers]
    return [outcome.receipt_directory(campaign) for campaign in last]


def identity(arm, code):
    environment = {key: value for key, value in arm["environment"].items()
                   if key not in INPUT_ENVIRONMENT}
    return arm["executable_sha256"], json.dumps(environment, sort_keys=True), code


def campaign(directory):
    """The verified campaign in `directory`: its summary and, per cell, outcome and arm sides."""
    verifier.verify(str(directory / "execution.log"), str(directory / "receipt.json"),
                    str(directory / "plan.json"))
    summary, _, cells = outcome.outcomes(directory)
    receipt = read(directory / "receipt.json")
    measured = {cell["cell_id"]: cell for cell in receipt["cells"]}
    reports = defaultdict(list)
    for row in smoke.diagnostics(directory):
        if DECODER_REPORT in row:
            reports[row["cell_id"], row["arm"]].append(row[DECODER_REPORT])
    rows = []
    for cell in cells:
        identifier = cell["summary"]["cell_id"]
        case = cell["planned"]["case"]
        sides = []
        for side in ("baseline", "candidate"):
            name = cell["planned"][f"{side}_arm"]
            executions = [pair[side] for pair in measured[identifier]["pairs"]]
            decoder = reports.get((identifier, name), [])
            probed = any("stage_probes" in report for report in decoder)
            sides.append({
                "side": side, "arm": name, "build": receipt["arms"][name]["build"],
                "identity": identity(receipt["arms"][name], case["code"]),
                "workers": sorted({execution["workers_observed"] for execution in executions}),
                "times": [execution["ns_per_call"] for execution in executions],
                "batch_fill": [execution["conversion"]["batch_fill_ns"]
                               for execution in executions] if probed else None,
                "workspace": sorted({size for report in decoder
                                     for size in report["workspace_bytes"]}) or None,
                "quality": measured[identifier]["decoder_quality"][side],
            })
        rows.append({**cell, "part": cell["declared"]["decoder"]["arm_kind"],
                     "family": summary["family"]["family_id"], "batch": case["batch_size"],
                     "code": case["code"], "sides": sides})
    return {"directory": directory, "summary": summary, "cells": rows}


def peak_memory(results):
    """Peak-memory rows of the record under `results`, keyed by arm identity and code."""
    found = [smoke.ROOT / path for path in smoke.listed("peak-memory.json")
             if (smoke.ROOT / path).is_relative_to(results)]
    if len(found) != 1:
        sys.exit(f"{len(found)} peak-memory records under {results}; exactly one must exist")
    record = read(found[0])
    rows = {}
    for arm in record["arms"].values():
        environment = json.dumps(arm["identity"].get("environment", {}), sort_keys=True)
        for measured in arm["codes"].values():
            rows[arm["identity"]["executable_sha256"], environment,
                 measured["case"]["code"]] = measured["samples_kib"]
    return {"path": found[0], "method": record["method"], "rows": rows}


def calibration():
    """The calibration campaign's verification record and the owner's field decisions."""
    sys.path.insert(0, str(CALIBRATION))
    try:
        verify = load(CALIBRATION / "verify-campaign.py")
    finally:
        sys.path.remove(str(CALIBRATION))
    record = verify.verification()
    archive = verify.evidence()[3]
    responses = json.loads(verify.pinned(archive, "/owner-decisions.json")[1])
    fields = [field for response in responses
              for field in json.loads(response["decisions"])["fields"]]
    return {"record": record, "fields": fields}


def profile(summary_path):
    """The profile summary after its series log verifies."""
    summary = read(summary_path)
    sessions = summarizer(summary_path).verified_sessions(summary_path.parent)
    if len(sessions) != summary["sessions"]:
        sys.exit(f"{summary_path}: {summary['sessions']} sessions summarized, "
                 f"{len(sessions)} verified")
    return {"path": summary_path, "summary": summary}


# ---------------------------------------------------------------------------- rendering

table = outcome.table


def ticked(value):
    return "n/a" if value is None else f"`{value}`"


def spread(values, scale=1.0):
    """`median [lower, upper]` of `values` divided by `scale`, with the interval coverage."""
    median, lower, upper, coverage = median_interval(values)
    return f"{median / scale:.0f} [{lower / scale:.0f}, {upper / scale:.0f}]", coverage


def per_call(side, frames=1):
    text, coverage = spread(side["times"], frames)
    return text, f"{len(side['times'])} ({coverage:.3f})"


def throughput(side, frames):
    median, lower, upper, _ = median_interval(side["times"])
    return f"{frames * 1e9 / median:.1f} [{frames * 1e9 / upper:.1f}, {frames * 1e9 / lower:.1f}]"


def frames_per_call(cell, side):
    return cell["batch"] * side["workers"][0] if len(side["workers"]) == 1 else None


def workers(side):
    return ", ".join(str(count) for count in side["workers"])


def arm_rows(cells):
    for cell in cells:
        for side in cell["sides"]:
            yield cell, side


def peak(side, memory):
    samples = memory["rows"].get(side["identity"])
    if samples is None:
        return "no row of the peak-memory record"
    text, coverage = spread(samples)
    return f"{text} ({len(samples)}, {coverage:.3f})"


def measurement_rows(cells, memory):
    rows = []
    for cell, side in arm_rows(cells):
        frames = frames_per_call(cell, side)
        time, executions = per_call(side)
        fill = (spread(side["batch_fill"])[0] if side["batch_fill"] is not None
                else "unmeasured: the arm reports no stage probe")
        rows.append([
            f"`{cell['family']}`", f"`{cell['summary']['cell_id']}`", side["side"],
            f"`{side['arm']}`", f"`{side['build']}`", cell["summary"]["core_arm"],
            workers(side), str(cell["batch"]), str(frames) if frames else "varies", executions,
            time, throughput(side, frames) if frames else "n/a", fill,
            ", ".join(map(str, side["workspace"])) if side["workspace"] else "not reported",
            peak(side, memory),
        ])
    return rows


def outcome_rows(cells):
    rows = []
    for cell in cells:
        recorded = cell["summary"]
        interval = recorded["interval"]
        rows.append([
            f"`{cell['family']}`", f"`{recorded['cell_id']}`", cell["declared"]["role"],
            cell["declared"]["objective"], recorded["core_arm"],
            str(len(recorded["resolved_cpus"])),
            str(cell["batch"]), f"`{cell['planned']['baseline_arm']}`",
            f"`{cell['planned']['candidate_arm']}`", str(interval["pairs"]),
            f"{interval['estimate']:.4f}",
            f"[{interval['lower']:.4f}, {interval['upper']:.4f}] at {interval['confidence']:.4f}",
            ticked(recorded["decision"]), ticked(recorded["outcome"]), cell["interpretation"],
        ])
    return rows


def latency_rows(cells):
    rows = []
    for cell, side in arm_rows(cells):
        if cell["batch"] == 1 and side["workers"] == [1]:
            time, executions = per_call(side)
            rows.append([f"`{cell['family']}`", f"`{cell['summary']['cell_id']}`", side["side"],
                         f"`{side['arm']}`", f"`{side['build']}`", executions, time])
    return rows


def sweep_rows(cells):
    rows = []
    for cell, side in arm_rows(cells):
        if cell["summary"]["core_arm"] == SINGLE_CORE and side["workers"] == [1]:
            time, executions = per_call(side, cell["batch"])
            rows.append(((cell["code"], side["arm"], side["build"], cell["batch"], cell["family"],
                          cell["summary"]["cell_id"]),
                         [f"`{cell['code']}`", f"`{side['arm']}`", f"`{side['build']}`",
                          str(cell["batch"]), f"`{cell['family']}`",
                          f"`{cell['summary']['cell_id']}`", executions, time]))
    return [row for _, row in sorted(rows, key=lambda keyed: keyed[0])]


def core_rows(cells):
    rows = []
    for cell, side in arm_rows(cells):
        if cell["summary"]["core_arm"] != SINGLE_CORE:
            frames = frames_per_call(cell, side)
            time, executions = per_call(side)
            rows.append([f"`{cell['family']}`", f"`{cell['summary']['cell_id']}`", side["side"],
                         f"`{side['arm']}`", cell["summary"]["core_arm"],
                         str(len(cell["summary"]["resolved_cpus"])), workers(side), executions,
                         time, throughput(side, frames) if frames else "n/a"])
    return rows


def quality_rows(cells):
    rows = []
    for cell in cells:
        if not any(side["build"] == EXTERNAL for side in cell["sides"]):
            continue
        for side in cell["sides"]:
            quality = side["quality"]
            settings, iterations = quality["settings"], quality["iterations"]
            fer = quality["fer_interval"]
            rows.append([
                f"`{cell['summary']['cell_id']}`", side["side"], f"`{side['arm']}`",
                settings["precision"], settings["schedule"],
                " ".join(str(part) for part in (settings["normalization"]["kind"],
                                                settings["normalization"]["factor"])
                         if part is not None),
                settings["stopping"]["kind"], str(settings["iteration_cap"]),
                str(quality["frames"]), str(quality["frame_errors"]),
                f"{quality['fer']:.4f} [{fer[0]:.4f}, {fer[1]:.4f}]",
                f"`{quality['interval_method']}`",
                f"{iterations['mean']:.2f} / {iterations['p50']} / {iterations['p90']} / "
                f"{iterations['max']}",
            ])
    return rows


def or_absent(rows, header, absent):
    return table(header, rows) if rows else [absent]


def part(place, kind, cells, memory):
    method = memory["method"]
    lines = [f"## {PARTS[kind]}", "",
             f"Cells whose addendum declares `decoder.arm_kind` `{kind}`.", "",
             "### Outcomes", "",
             "Speedup and interval are the acceptance summary's: the baseline arm's median time "
             "per call over the candidate arm's, above 1 favouring the candidate, with the "
             "percentile-bootstrap interval at the stated confidence. Decision and outcome are "
             "as the evaluator records them; the interpretation is `make-collection-outcome.py`'s.",
             "",
             *table(["Family", "Cell", "Role", "Objective", "Core arm", "CPUs", "Batch",
                     "Baseline arm", "Candidate arm", "Pairs", "Speedup", "Interval",
                     "Decision", "Outcome", "Interpretation"], outcome_rows(cells)), "",
             "### Arm measurements", "",
             "Time per call is in nanoseconds, median [order-statistic interval] over the cell's "
             "executions, whose count and interval coverage the Executions column gives; one call "
             "dispatches one batch to each worker. Throughput is frames per call over that time "
             "and over the interval's ends. Batch fill is the arm's per-execution "
             "`conversion.batch_fill_ns`, the median of its stage probes of the decoder call at a "
             "zero iteration cap, summarized the same way. Lane workspace is the decoder's "
             "`workspace_bytes` per worker as the arm's diagnostics report it. Peak RSS is the "
             f"{method['quantity']} ({method['scope']}) in the row of "
             f"{link(place, memory['path'])} with the arm's executable digest, environment and "
             "code, in KiB, median [order-statistic interval] (launches, coverage).", "",
             *table(["Family", "Cell", "Side", "Arm", "Build", "Core arm", "Workers", "Batch",
                     "Frames per call", "Executions", "Time per call, ns",
                     "Throughput, frames/s", "Batch fill, ns", "Lane workspace, bytes per worker",
                     "Peak RSS, KiB"], measurement_rows(cells, memory)), "",
             "### Single-frame latency", "",
             "Arms of cells that decode a batch of one frame on one worker; time per call in "
             "nanoseconds as above.", "",
             *or_absent(latency_rows(cells),
                        ["Family", "Cell", "Side", "Arm", "Build", "Executions",
                         "Time per call, ns"],
                        "No cell of this part decodes a batch of one frame on one worker, so it "
                        "measures no single-frame latency."), "",
             "### Batch-size sweep", "",
             "Arms of single-core cells by code, arm, build and batch size; time per frame is the "
             "time per call over the batch size, in nanoseconds. Rows of different campaigns are "
             "separate measurements.", "",
             *table(["Code", "Arm", "Build", "Batch", "Family", "Cell", "Executions",
                     "Time per frame, ns"], sweep_rows(cells)), "",
             "### Physical-core and SMT cells", "",
             "Arms of cells on more than one core: `physical-cores-*` arms pin one worker per "
             "physical core and `logical-cpus-*` arms one per logical CPU, SMT siblings included.",
             "",
             *or_absent(core_rows(cells),
                        ["Family", "Cell", "Side", "Arm", "Core arm", "CPUs", "Workers",
                         "Executions", "Time per call, ns", "Throughput, frames/s"],
                        "No cell of this part runs on more than one core."), ""]
    quality = quality_rows(cells)
    if quality:
        lines += ["### Decoder quality", "",
                  "Per-frame quality of each arm of the cells with an external arm, from the "
                  "receipt's `decoder_quality`: FER with its interval by the stated method; "
                  "iterations mean / p50 / p90 / max over the frames, descriptive. Iteration "
                  "counts under different schedules or stopping contracts are not comparable.", "",
                  *table(["Cell", "Side", "Arm", "Precision", "Schedule", "Update rule",
                          "Stopping", "Iteration cap", "Frames", "Frame errors", "FER",
                          "Interval method", "Iterations"], quality), ""]
    return lines


def campaign_rows(place, campaigns):
    rows = []
    for found in campaigns:
        summary, directory = found["summary"], found["directory"]
        kinds = sorted({cell["part"] for cell in found["cells"]})
        rows.append([
            f"`{summary['family']['family_id']}`",
            link(place, directory, f"`{summary['campaign_id']}`"), summary["label"],
            ", ".join(PARTS[kind] for kind in kinds), f"`{summary['verdict']}`",
            f"`{str(summary['qualifies']).lower()}`", str(len(summary["findings"])),
            str(summary["sessions"]), link(place, directory / "execution.log", "verified"),
        ])
    return rows


def finding_rows(campaigns):
    return [[f"`{found['summary']['campaign_id']}`", finding["rule"], finding["severity"],
             ticked(finding.get("cell")), finding["message"]]
            for found in campaigns for finding in found["summary"]["findings"]]


def calibration_section(place, calibrated):
    record = calibrated["record"]
    journal, owner = record["journal"], record["owner_envelope"]
    return [
        "## Decode selector calibration", "",
        f"Campaign `{record['campaign_id']}`, verified from its execution journal "
        f"`{record['execution_log']['path']}` in the committed evidence archive by "
        f"{link(place, CALIBRATION / 'verify-campaign.py', '`verify-campaign.py`')}: "
        f"declared cells {journal['declared']['cells']}, units {journal['declared']['units']}, "
        f"sessions {journal['sessions']}, terminal record `{journal['terminal']}`. Its owner "
        f"envelope is {link(place, smoke.ROOT / owner['path'])} with the receipt "
        f"{link(place, smoke.ROOT / owner['receipt'])}. The holdout family's `tuned-portable` and "
        "`native` arms install this envelope; its `conservative-portable` arms install none.", "",
        "Field decisions as the owner records them; their scores are the producer's descriptive "
        "statistic, carry no interval and stay in the receipt.", "",
        *table(["Field", "Reason", "Selected", "Emitted", "Grid-boundary limited"],
               [[f"`{field['field']}`", f"`{field['decision']['reason']}`",
                 str(field["selected"]), f"`{str(field['emitted']).lower()}`",
                 f"`{str(field['decision']['grid_boundary_limited']).lower()}`"]
                for field in calibrated["fields"]]), "",
    ]


def profile_section(place, series):
    summary, path = series["summary"], series["path"]
    stats = []
    for label, case in summary["stats"].items():
        metric = case["metrics"]["ns_per_frame_per_worker"]
        stats.append([f"`{label}`", case["arm"], f"`{case['code']}`", case["core_arm"],
                      ", ".join(map(str, case["workers_observed"])), str(metric["n"]),
                      f"{metric['median']:.0f} [{metric['lower']:.0f}, {metric['upper']:.0f}]",
                      f"{metric['coverage']:.3f}"])
    ratios = [[f"`{ratio['id']}`", ratio["kind"], f"{ratio['estimate']:.3f}",
               f"[{ratio['lower']:.3f}, {ratio['upper']:.3f}]", str(ratio["seed"])]
              for ratio in summary["ratios"]]
    return [
        "## Profile series", "",
        f"The summary {link(place, path)} of the series `{summary['source']}`, whose "
        f"`repetitions.log` records {summary['sessions']} sessions done under the first "
        "session's identity and the terminal `series done` record. Time per frame per worker in "
        "nanoseconds, median [order-statistic interval] over sessions; ratios of medians with "
        "the summary's percentile-bootstrap interval and seed.", "",
        *table(["Case", "Route", "Code", "Core arm", "Workers", "Sessions",
                "Time per frame per worker, ns", "Coverage"], stats), "",
        *table(["Ratio", "Kind", "Estimate", "Interval", "Seed"], ratios), "",
    ]


def render(place, campaigns, memory, calibrated, series):
    """The tables, written to be read at `place`."""
    cells = [cell for found in campaigns for cell in found["cells"]]
    unknown = sorted({cell["part"] for cell in cells} - set(PARTS))
    if unknown:
        raise KeyError(f"cells of undeclared arm kinds: {', '.join(unknown)}")
    lines = [
        TITLE, "", "> **Diátaxis Type:** Reference", "",
        f"Generated by {link(place, pathlib.Path(__file__), f'`{pathlib.Path(__file__).name}`')} "
        "from the committed receipts, plans, execution logs and records it names below; from the "
        f"worktree root, `{pathlib.Path(__file__).name} {generator.repository_path(place)}` "
        "regenerates it. External arms are AFF3CT [Cassagne2019] executables; each arm's identity "
        "is its receipt entry.", "",
        "## Campaigns", "",
        "The campaign each family ledger names last. Each execution log is verified by "
        f"{link(place, pathlib.Path(verifier.__file__), '`verify-campaign-log.py`')}"
        " before these tables are written; verdict, qualification and finding count are the "
        "acceptance summary's.", "",
        *table(["Family", "Campaign", "Label", "Comparison", "Verdict", "Qualifies", "Findings",
                "Sessions", "Execution log"], campaign_rows(place, campaigns)), "",
        "### Findings", "",
        *or_absent(finding_rows(campaigns), ["Campaign", "Rule", "Severity", "Cell", "Message"],
                   "No acceptance summary records a finding."), "",
    ]
    for kind in PARTS:
        selected = [cell for cell in cells if cell["part"] == kind]
        if selected:
            lines += part(place, kind, selected, memory)
    lines += calibration_section(place, calibrated)
    lines += profile_section(place, series)
    while lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    if pathlib.Path.cwd() != smoke.ROOT:
        sys.exit("invoke from the worktree root")
    out = pathlib.Path(sys.argv[1]).resolve()
    results = out.parent
    campaigns = [campaign(directory) for directory in outcome_directories(results)]
    series = profile(profile_summary())
    text = render(out, campaigns, peak_memory(results), calibration(), series)
    outcome.write(out, text)
    print(generator.repository_path(out))


if __name__ == "__main__":
    main()
