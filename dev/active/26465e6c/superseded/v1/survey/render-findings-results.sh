#!/usr/bin/env bash
# Renders the findings' measured-results tables from the committed acceptance
# summaries (jit:26465e6c).
#
#   dev/active/26465e6c/survey/render-findings-results.sh
#
# Every figure in findings.md's results tables is a projection of an accepted
# receipt under dev/bench_results/26465e6c/, never a transcribed number. The
# script replaces the block between the RESULTS-TABLE markers in findings.md, so
# re-running it after a new receipt lands keeps the prose from going stale.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKTREE="$(git -C "${HERE}" rev-parse --show-toplevel)"
cd "${WORKTREE}"

python3 - <<'PY_RENDER'
import glob, json, os, re

BEGIN = "<!-- RESULTS-TABLE:begin (generated by survey/render-findings-results.sh) -->"
END = "<!-- RESULTS-TABLE:end -->"
FINDINGS = "dev/active/26465e6c/findings.md"

def load(directory):
    with open(f"{directory}/acceptance-summary.json") as handle:
        return json.load(handle)

lines = []
for directory in sorted(glob.glob("dev/bench_results/26465e6c/*/")):
    directory = directory.rstrip("/")
    if not os.path.exists(f"{directory}/acceptance-summary.json"):
        continue
    summary = load(directory)
    family = summary["family"]
    lines.append(f"### `{family['family_id']}` -- {summary['label']}")
    lines.append("")
    lines.append(f"Receipt [`{directory}`]({os.path.relpath(directory, 'dev/active/26465e6c')}), "
                 f"campaign `{summary['campaign_id']}`, verdict **{summary['verdict']}**, "
                 f"qualifies for production selection: **{str(summary['qualifies']).lower()}**, "
                 f"{summary['sessions']} session(s), resumed {str(summary['resumed']).lower()}. "
                 f"Receipt digest `{summary['receipt_sha256']}`.")
    lines.append("")
    lines.append(f"Family-wise alpha {family['family_alpha']} over {family['comparisons']} "
                 f"comparison(s) gives a per-comparison confidence of "
                 f"{family['per_comparison_confidence']:.6f}; every interval below is a "
                 f"{family['bootstrap_resamples']}-resample percentile bootstrap over whole pairs "
                 f"at that confidence. A speedup above 1 favours the candidate, so a value above 1 "
                 f"means the candidate ran faster than gf2's own arm.")
    lines.append("")
    lines.append("| Cell | Candidate outcome | Pairs | Flagged windows | Speedup of medians | Interval | Decision |")
    lines.append("|---|---|---:|---:|---:|---|---|")
    for cell in summary["cells"]:
        interval = cell.get("interval")
        if interval:
            estimate = f"{interval['estimate']:.4f}"
            bounds = f"[{interval['lower']:.4f}, {interval['upper']:.4f}]"
            pairs = str(interval["pairs"])
        else:
            estimate = bounds = "n/a"
            pairs = "0"
        flagged = f"{cell['flagged_windows']}/{cell['total_windows']}"
        decision = cell["decision"] or "n/a"
        note = cell.get("reason")
        outcome = f"**{cell['outcome']}**" + (f" ({note})" if note else "")
        lines.append(f"| `{cell['cell_id']}` | {outcome} | {pairs} | {flagged} | {estimate} | {bounds} | {decision} |")
    if summary["findings"]:
        lines.append("")
        lines.append("Findings raised by the acceptance tool:")
        for finding in summary["findings"]:
            lines.append(f"- `{finding.get('rule')}` {finding.get('severity')}: {finding.get('message')}")
    lines.append("")

with open(FINDINGS) as handle:
    text = handle.read()
block = BEGIN + "\n\n" + "\n".join(lines).rstrip() + "\n\n" + END
if BEGIN in text:
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
else:
    raise SystemExit(f"{FINDINGS} carries no RESULTS-TABLE markers")
with open(FINDINGS, "w") as handle:
    handle.write(text)
print(f"rendered {sum(1 for line in lines if line.startswith('| `'))} cell rows into {FINDINGS}")
PY_RENDER
