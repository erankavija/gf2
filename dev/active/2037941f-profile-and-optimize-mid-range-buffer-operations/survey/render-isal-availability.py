#!/usr/bin/env python3
"""Render the external dispatch row from the committed ISA-L qualification."""

import hashlib
import json
import pathlib
import sys


ROOT = pathlib.Path(__file__).resolve().parents[4]
STORY = pathlib.Path("dev/active/2037941f-profile-and-optimize-mid-range-buffer-operations")
VALIDATION = STORY / "survey/logical-harness-validation.txt"
PROBE = STORY / "isal-probe-record.txt"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: render-isal-availability.py OUTPUT")
    validation = (ROOT / VALIDATION).read_bytes()
    probe = (ROOT / PROBE).read_bytes()
    records = [
        json.loads(line[2:])
        for line in validation.decode().splitlines()
        if line.startswith("# {") and '"library":"isa-l"' in line
    ]
    if len(records) != 1 or b"nasm=absent; public dispatched xor_gen is unavailable" not in probe:
        raise ValueError("ISA-L qualification does not establish dispatch unavailability")
    record = records[0]
    if (
        record["qualified_label"] != "xor_gen_base/scalar"
        or record["runtime_dispatch"]
        or record["public_xor_gen_available"]
        or record["unavailable_row"] != "isal-dispatched-xor-gen"
    ):
        raise ValueError("ISA-L qualification changed its dispatch contract")
    output = pathlib.Path(sys.argv[1])
    output.write_text(
        "# ISA-L dispatch availability\n\n"
        "> **Diátaxis Type:** Reference\n\n"
        "Generated by `survey/render-isal-availability.py` from the committed "
        "qualification records. This external route has no runner workload.\n\n"
        f"Source: `{VALIDATION}` (SHA-256 `{hashlib.sha256(validation).hexdigest()}`); "
        f"`{PROBE}` (SHA-256 `{hashlib.sha256(probe).hexdigest()}`).\n\n"
        "| Route | Status | Samples | Reason |\n"
        "|---|---|---:|---|\n"
        f"| `{record['unavailable_row']}` | unavailable | 0 | "
        f"{record['unavailable_reason']} |\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
