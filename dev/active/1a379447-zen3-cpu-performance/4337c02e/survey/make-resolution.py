#!/usr/bin/env python3
"""Apply the frozen pilot-resolution rule to the lane-threshold pilot (jit:4337c02e).

Usage: make-resolution.py <survey-analysis executable> <dense-campaign executable>,
from the worktree root.

The rule is the *Margins and resolution* section of the lane-threshold
addendum, applied through the dense story's shared `resolution_rule`. The
record states the outcome the rule fixes, `eligible` or
`resolution-insufficient`, and the whole pilot's widest cell, which the rule
excludes. The standard output line carries the resolution and the outcome for
the freeze script.
"""

import hashlib
import json
import re
import subprocess
import sys

sys.dont_write_bytecode = True

from budget import budget, listing  # noqa: E402
from locate import HERE, PILOT, ROOT, repo_artifacts  # noqa: E402
from resolution_rule import accepted_pilot, ceiling, half_widths, rounded  # noqa: E402

RULES = (HERE.parent / "matvec-lane-threshold-addendum.md").relative_to(ROOT)
OUTPUT = HERE.parent / "pilot-resolution.md"
WIDEST = re.compile(r"pilot\s+alpha\s+\S+\s+widest\s+([0-9.]+)\s+in\s+(\S+)")


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    analysis, campaign_tool = sys.argv[1:]
    pilot = repo_artifacts.receipt(PILOT)
    addendum_path = repo_artifacts.addendum(PILOT)
    receipt, record = accepted_pilot(pilot)
    addendum = json.loads((ROOT / addendum_path).read_bytes())
    measured = {cell["cell_id"]: len(cell["pairs"]) for cell in record["cells"]}
    ids = [
        cell_id for cell_id, row in listing(campaign_tool).items() if row["confirmatory"] == "true"
    ]
    if not ids or any(cell_id not in measured for cell_id in ids):
        raise SystemExit("the pilot lacks a confirmatory cell of the frozen addendum")

    spent = budget(addendum, len(ids), through=record["campaign_id"])
    if len(ids) > spent["capacity"]:
        raise SystemExit("P-20 admits fewer comparisons than the family's confirmatory cells")
    alpha = spent["corrected"]
    widths = half_widths(analysis, pilot, alpha)
    if any(cell_id not in widths for cell_id in ids):
        raise SystemExit("canonical resolution output lacks a confirmatory cell")
    maximum = max(widths[cell_id] for cell_id in ids)
    resolution = rounded(maximum)
    limit = ceiling(RULES, "lane threshold")
    eligible = resolution <= limit
    outcome = "eligible" if eligible else "resolution-insufficient"

    command = [analysis, "resolution", str(pilot), format(alpha, ".12g")]
    whole = WIDEST.search(subprocess.check_output(command, cwd=ROOT, text=True))
    if not whole:
        raise SystemExit("canonical resolution output states no whole-pilot width")
    if not eligible:
        consequence = (
            "The frozen family rule ends this family after its exploratory pilot. "
            "No confirmatory reservation is made and the threshold stays unchanged."
        )
    else:
        consequence = (
            "The pilot resolves the family within its frozen ceiling. The canonical freezer "
            "pins this resolution in the confirmation addendum."
        )
    rows = "\n".join(f"| `{cell}` | {measured[cell]} | {widths[cell]:.6f} |" for cell in ids)
    ledger = addendum["family_wise"]["ledger_path"]
    OUTPUT.write_text(
        "# Lane-threshold pilot resolution\n\n"
        "> **Diátaxis Type:** Reference\n\n"
        f"Generated by `survey/make-resolution.py` from `{pilot}/receipt.json` "
        f"(SHA-256 `{hashlib.sha256(receipt).hexdigest()}`); frozen rule: "
        f"[`{RULES.name}`]({RULES.name}), *Margins and resolution*.\n\n"
        "The canonical `survey-analysis resolution` command recomputes whole-pair "
        "bootstrap intervals at the first confirmation's corrected alpha.\n\n"
        f"Command: `survey-analysis resolution {pilot} {alpha:.12g}`\n\n"
        f"Ledger `{ledger}` through the pilot: {spent['entries']} reservation(s), "
        f"{spent['comparisons'] - len(ids)} reserved comparison(s), so the confirmation is "
        f"attempt $t={spent['attempt']}$ with $\\alpha_t={spent['attempt_alpha']:g}$. P-20 "
        f"requires {spent['tail_draws']} expected bootstrap draws per tail, which admits "
        f"{spent['capacity']} further comparison(s) at {spent['resamples']} resamples. The "
        f"family's $m={len(ids)}$ confirmatory cells give $\\alpha_c={alpha:.6g}$ and "
        f"{spent['draws']:.4g} expected draws per tail.\n\n"
        "| Confirmatory cell | Pilot pairs | Relative half-width |\n|---|---:|---:|\n"
        f"{rows}\n\n"
        f"Largest confirmatory width: {maximum:.6f}; frozen upward rounding to 0.001: "
        f"$r={resolution:.3f}$. Family ceiling: {limit:.3f}.\n\n"
        f"**Outcome: `{outcome}`.** {consequence}\n\n"
        f"The exploratory cells take no part in $r$. The widest relative half-width of the "
        f"whole pilot at the pilot's alpha is {float(whole.group(1)):.6f}, in "
        f"`{whole.group(2)}`.\n",
        encoding="utf-8",
    )
    print(f"resolution={resolution:.3f} outcome={outcome}")


if __name__ == "__main__":
    main()
