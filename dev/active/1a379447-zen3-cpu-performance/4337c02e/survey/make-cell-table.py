#!/usr/bin/env python3
"""Tabulate the lane-threshold family's cells (jit:4337c02e).

Usage: make-cell-table.py <dense-campaign executable>, from the worktree root.

The table joins the committed pilot campaign addendum with the harness's own
cell listing (`dense-campaign list`), which names each cell's arms and whether
the frozen addendum makes it confirmatory. The comparison arithmetic reads the
resample count, the P-20 tail rule and the attempt allocation from the
campaign-support sources and the reservations from the family ledger through
the pilot's line, so it states the first confirmation's budget. The
table fails when a cell sits at a stride the holdout declaration of `63bad95d`
reserves.
"""

import json
import sys

sys.dont_write_bytecode = True

from budget import budget, listing  # noqa: E402
from locate import FAMILY, HERE, PILOT, ROOT, repository_files  # noqa: E402

CAMPAIGN = HERE.parent / "campaigns" / "matvec-simd-threshold.json"
OUTPUT = HERE.parent / "cell-table.md"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    addendum = json.loads(CAMPAIGN.read_bytes())
    listed = listing(sys.argv[1])
    declared = [cell["cell_id"] for cell in addendum["cells"]]
    if set(declared) != set(listed):
        raise SystemExit("the campaign addendum and the harness listing name different cells")

    confirmatory = [cell for cell in declared if listed[cell]["confirmatory"] == "true"]
    spent = budget(addendum, len(confirmatory), through=PILOT)
    tail_draws, draws = spent["tail_draws"], spent["draws"]

    holdout = repository_files.live_file(ROOT, "matvec-holdout-cells.json")
    reserved = set(json.loads((ROOT / holdout).read_bytes())["reserved_stride_words"])
    strides = {cell["workload"]["size"]["words"] for cell in addendum["cells"]}
    if strides & reserved:
        raise SystemExit(f"cells sit at reserved strides {sorted(strides & reserved)}")

    effect = addendum["effect"]
    lines = [
        "# Lane-threshold cells",
        "",
        "> **Diátaxis Type:** Reference",
        "",
        "Generated by `survey/make-cell-table.py` from",
        f"[`campaigns/{CAMPAIGN.name}`](campaigns/{CAMPAIGN.name}), the harness listing of",
        f"`{FAMILY}` and the family ledger `{addendum['family_wise']['ledger_path']}`",
        f"through the line of `{PILOT}`.",
        "",
        "## Family",
        "",
        "| Setting | Value |",
        "|---|---|",
        f"| Family | `{FAMILY}` |",
        f"| Purpose | {addendum['family']['purpose']} |",
        f"| Worthwhile speedup | {effect['worthwhile_speedup']} |",
        f"| Equivalence margin | {effect['equivalence_margin']} |",
        f"| Ledger entries, spending reservations | {spent['entries']}, {spent['spending']} |",
        f"| Confirmation attempt | {spent['attempt']} |",
        f"| Confirmatory cells, cumulative comparisons | {len(confirmatory)}, {spent['comparisons']} |",
        f"| Attempt alpha | {spent['attempt_alpha']:.6g} |",
        f"| Corrected alpha | {spent['corrected']:.6g} |",
        f"| Expected draws per bootstrap tail (P-20 needs {tail_draws}) | {draws:.4g} |",
        f"| Strides `{holdout}` reserves | {', '.join(map(str, sorted(reserved)))} |",
        f"| Strides of this family | {', '.join(map(str, sorted(strides)))} |",
        "",
        "## Cells",
        "",
        "Every cell is exploratory in the pilot. The confirmation measures the cells marked",
        "confirmatory, on fresh pairs. A speedup above one favours the candidate arm.",
        "",
        "| Ordinal | Cell | Stride (words) | Rows | Columns | Cache | Objective | Confirmatory | Baseline arm | Candidate arm | Seed |",
        "|---:|---|---:|---:|---:|---|---|---|---|---|---|",
    ]
    for cell in addendum["cells"]:
        row = listed[cell["cell_id"]]
        size = cell["workload"]["size"]
        baseline, candidate = row["arms"].split(",")
        if cell["objective"] != row["objective"] or cell["cache_state"] != row["cache"]:
            raise SystemExit(f"{cell['cell_id']}: the addendum and the listing disagree")
        lines.append(
            f"| {row['ordinal']} | `{cell['cell_id']}` | {size['words']} | {size['rows']} "
            f"| {size['columns']} | {cell['cache_state']} | {cell['objective']} "
            f"| {'yes' if row['confirmatory'] == 'true' else 'no'} | `{baseline}` | `{candidate}` "
            f"| `{row['seed']}` |"
        )
    if draws < tail_draws:
        raise SystemExit(f"{draws} expected draws per tail is below P-20's {tail_draws}")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(declared)} cells, {len(confirmatory)} confirmatory")


if __name__ == "__main__":
    main()
