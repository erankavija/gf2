#!/usr/bin/env python3
"""Apply the frozen pilot-resolution rule to the ragged-tail pilot (jit:7dbe1393).

Usage: make-resolution.py <survey-analysis executable> <dense-campaign executable>
[family], from the worktree root. The family defaults to the first ragged-tail
family; the repeat family applies the first family's rule to its own pilot and
writes `pilot-resolution-v2.md`.

The rule is the *Margins and resolution* section of the ragged-tail addendum,
applied through the dense story's shared `resolution_rule` and the
lane-threshold family's comparison `budget`. Every pilot cell is confirmatory,
so the rule's scope is the whole pilot. The record states the outcome the rule
fixes, `eligible` or `resolution-insufficient`, and the host load each pilot
session observed at its start. The standard output line carries the resolution
and the outcome for the freeze.
"""

import hashlib
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True

from locate import FAMILY, HERE, REPEAT_FAMILY, ROOT, repository_files  # noqa: E402

for shared in ("repo_artifacts.py", "budget.py"):
    sys.path.append(str(ROOT / Path(repository_files.live_file(ROOT, shared)).parent))
import repo_artifacts  # noqa: E402
from budget import budget, listing  # noqa: E402
from resolution_rule import accepted_pilot, ceiling, half_widths, rounded  # noqa: E402

RULES = (HERE.parent / "matvec-ragged-tail-addendum.md").relative_to(ROOT)
OUTPUTS = {
    FAMILY: HERE.parent / "pilot-resolution.md",
    REPEAT_FAMILY: HERE.parent / "pilot-resolution-v2.md",
}


def session_loads(pilot):
    """Each session's start time and load averages from the pilot's execution log."""
    rows = []
    for line in (ROOT / pilot / "execution.log").read_text().splitlines():
        event = json.loads(line)
        details = event.get("details") or {}
        if event["event"] == "driver-diagnostic" and details.get("kind") == "host-observation":
            observation = details["observation"]
            loads = " / ".join(f"{load:.2f}" for load in observation["load_average"])
            rows.append(f"| `{event['session_id']}` | {observation['observed_utc']} | {loads} |")
    return rows


def main():
    if len(sys.argv) not in (3, 4):
        raise SystemExit(__doc__)
    analysis, campaign_tool = sys.argv[1:3]
    family = sys.argv[3] if len(sys.argv) == 4 else FAMILY
    output = OUTPUTS[family]
    pilot = repo_artifacts.receipt(f"v4-r1-{family}")
    receipt, record = accepted_pilot(pilot)
    addendum = json.loads((ROOT / repo_artifacts.addendum(f"v4-r1-{family}")).read_bytes())
    measured = {cell["cell_id"]: len(cell["pairs"]) for cell in record["cells"]}
    ids = [
        cell_id for cell_id, row in listing(campaign_tool).items() if row["confirmatory"] == "true"
    ]
    if sorted(ids) != sorted(measured):
        raise SystemExit("the pilot's cells are not the family's confirmatory cells")

    spent = budget(addendum, len(ids), through=record["campaign_id"])
    if len(ids) > spent["capacity"]:
        raise SystemExit("P-20 admits fewer comparisons than the family's confirmatory cells")
    alpha = spent["corrected"]
    widths = half_widths(analysis, pilot, alpha)
    if any(cell_id not in widths for cell_id in ids):
        raise SystemExit("canonical resolution output lacks a confirmatory cell")
    widest = max(ids, key=widths.get)
    resolution = rounded(widths[widest])
    limit = ceiling(RULES, "ragged tail")
    eligible = resolution <= limit
    outcome = "eligible" if eligible else "resolution-insufficient"
    if eligible:
        consequence = (
            "The pilot resolves the family within its frozen ceiling. The canonical freezer "
            "pins this resolution in the confirmation addendum."
        )
    else:
        consequence = (
            "The frozen family rule ends this family after its exploratory pilot: it runs no "
            "confirmation, makes no confirmatory reservation, and production keeps its kernel."
        )
    rows = "\n".join(f"| `{cell}` | {measured[cell]} | {widths[cell]:.6f} |" for cell in ids)
    ledger = addendum["family_wise"]["ledger_path"]
    output.write_text(
        f"# Ragged-tail pilot resolution, family `{family}`\n\n"
        "> **Diátaxis Type:** Reference\n\n"
        f"Generated by `survey/make-resolution.py` from `{pilot}/receipt.json` "
        f"(SHA-256 `{hashlib.sha256(receipt).hexdigest()}`); frozen rule: "
        f"[`{RULES.name}`]({RULES.name}), *Margins and resolution*.\n\n"
        "The canonical `survey-analysis resolution` command recomputes whole-pair "
        "bootstrap intervals at the first confirmation's corrected alpha.\n\n"
        f"Command: `survey-analysis resolution {pilot} {alpha:.12g}`\n\n"
        f"Ledger `{ledger}` through the pilot: {spent['entries']} reservation(s), "
        f"{spent['comparisons'] - len(ids)} reserved comparison(s), so a confirmation is "
        f"attempt $t={spent['attempt']}$ with $\\alpha_t={spent['attempt_alpha']:g}$. P-20 "
        f"requires {spent['tail_draws']} expected bootstrap draws per tail, which admits "
        f"{spent['capacity']} further comparison(s) at {spent['resamples']} resamples. The "
        f"family's $m={len(ids)}$ confirmatory cells give $\\alpha_c={alpha:.6g}$ and "
        f"{spent['draws']:.4g} expected draws per tail.\n\n"
        "| Confirmatory cell | Pilot pairs | Relative half-width |\n|---|---:|---:|\n"
        f"{rows}\n\n"
        f"Largest width: {widths[widest]:.6f}, in `{widest}`; frozen upward rounding to "
        f"0.001: $r={resolution:.3f}$. Family ceiling: {limit:.3f}.\n\n"
        f"**Outcome: `{outcome}`.** {consequence}\n\n"
        "## Host load at each pilot session\n\n"
        "The runner observes the host at each session start and writes the observation to "
        f"`{pilot}/execution.log` (`host-observation`, `load_average`).\n\n"
        "| Session | Observed UTC | Load average, 1 / 5 / 15 min |\n|---|---|---|\n"
        + "\n".join(session_loads(pilot))
        + "\n",
        encoding="utf-8",
    )
    print(f"resolution={resolution:.3f} outcome={outcome}")


if __name__ == "__main__":
    main()
