#!/usr/bin/env python3
"""Projects the profile's counters and call graphs into one Markdown page.

Reads the `perf stat` outputs and `perf report` outputs a profile run wrote and
prints, per counter case, the derived ratios the findings cite (instructions
per cycle, front-end stalled cycles per cycle, branch misses per branch, L1
load misses per load, last-level misses per reference) and, per call-graph
case, the symbols above a share threshold. Every figure is computed from the
file it sits beside; nothing is typed in.

Usage: summarize-attribution.py <profile-dir>
"""

import pathlib
import re
import sys

EVENT = re.compile(r"^\s*([\d,]+)\s+(\S+?)(?::u)?\s")
SHARE = re.compile(r"^\s+(\d+\.\d+)%\s+\S+\s+(\S+)\s+\[\.\]\s+(.*)$")


def events(path):
    values = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = EVENT.match(line)
        if match:
            values[match.group(2)] = int(match.group(1).replace(",", ""))
    return values


def ratio(numerator, denominator):
    return numerator / denominator if denominator else float("nan")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = pathlib.Path(sys.argv[1])
    print("# Counter ratios and sampled shares of the consumer profile")
    print()
    print(
        "Generated by `dev/active/04b85d10/survey/summarize-attribution.py` from the "
        "`perf-stat/` and `perf-report/` files beside it. Counters are user-space "
        "events over one whole `consumer-profile` run of the named case (preparation "
        "included); the generic backend-stall event is unavailable on this host, so no "
        "backend-stall ratio is derived. Sampled shares are 999 Hz cycle samples of one "
        "run and carry no inferential interval."
    )
    print()
    print("## Counter ratios")
    print()
    print("| Case | Cycles (G) | Instructions (G) | IPC | Front-end stalled cycles / cycle | Branch misses / branch | L1d load misses / load | LLC misses / reference |")
    print("|---|---:|---:|---:|---:|---:|---:|---:|")
    cases = sorted({p.name.rsplit(".", 2)[0] for p in (root / "perf-stat").glob("*.core.txt")})
    for case in cases:
        core = events(root / "perf-stat" / f"{case}.core.txt")
        memory = events(root / "perf-stat" / f"{case}.memory.txt")
        cycles = core.get("cycles", 0)
        print(
            f"| `{case}` | {cycles / 1e9:.2f} | {core.get('instructions', 0) / 1e9:.2f} | "
            f"{ratio(core.get('instructions', 0), cycles):.2f} | "
            f"{100 * ratio(core.get('stalled-cycles-frontend', 0), cycles):.2f}% | "
            f"{100 * ratio(core.get('branch-misses', 0), core.get('branches', 0)):.3f}% | "
            f"{100 * ratio(memory.get('L1-dcache-load-misses', 0), memory.get('L1-dcache-loads', 0)):.2f}% | "
            f"{100 * ratio(memory.get('cache-misses', 0), memory.get('cache-references', 0)):.2f}% |"
        )
    print()
    print("## Sampled shares (symbols at or above 1% of samples)")
    print()
    for path in sorted((root / "perf-report").glob("*.txt")):
        if path.name.endswith(".run.txt"):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        samples = next((line.strip() for line in text.splitlines() if line.startswith("# Samples")), "")
        print(f"### `{path.stem}` ({samples.lstrip('# ')})")
        print()
        print("| Share | Object | Symbol |")
        print("|---:|---|---|")
        for line in text.splitlines():
            match = SHARE.match(line)
            if match and float(match.group(1)) >= 1.0:
                symbol = match.group(3).replace("|", "\\|")
                print(f"| {match.group(1)}% | {match.group(2)} | `{symbol}` |")
        print()


if __name__ == "__main__":
    main()
