#!/usr/bin/env python3
"""Render the repeated DVB-T2 consumer profile into deterministic Markdown."""

import importlib.util
import json
import pathlib
import sys

_tables = pathlib.Path(__file__).with_name("make-dvb-tables.py")
_spec = importlib.util.spec_from_file_location("dvb_profile_tables", _tables)
assert _spec and _spec.loader
_module = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_module)
order_statistic = _module.order_statistic
MODCODS = _module.MODCODS


def number(value):
    if value >= 1000:
        return f"{value:,.0f}".replace(",", " ")
    if value >= 10:
        return f"{value:.1f}"
    return f"{value:.3f}"


def main():
    root = pathlib.Path(sys.argv[1])
    session_paths = sorted(root.glob("rep-*/cases.json"))
    if not session_paths:
        raise SystemExit(f"no completed profile sessions under {root}")
    sessions = [json.loads(path.read_text()) for path in session_paths]
    ladder = [case["id"] for case in json.loads((root / "ladder.json").read_text())]
    by_case = {case: [] for case in ladder}
    for path, session in zip(session_paths, sessions, strict=True):
        records = {record["id"]: record for record in session}
        if len(session) != len(ladder) or set(records) != set(ladder):
            raise ValueError(f"{path}: case records differ from the profile ladder")
        for case in ladder:
            by_case[case].append(records[case])
    coverage = order_statistic([row["ns_per_call"] for row in by_case[ladder[0]]])[3]

    print("# DVB-T2 interleaver dynamic profile")
    print()
    print("> **Diátaxis Type:** Reference")
    print()
    print(
        f"Generated by `summarize-profile.py` from {len(sessions)} completed session records. "
        "This projection reads retained `rep-NN/cases.json` records; the "
        f"[profile provenance](../{root.name}-provenance.md) pins the measured executable "
        "and producing inputs. Each session contributes the median of five 40 ms windows. "
        "The time intervals below use the same order-statistic method as the attribution "
        f"tables, with coverage {coverage:.3f} for {len(sessions)} sessions. The allocation "
        "counter adds relaxed atomics, so these wall times explain composition only; "
        "the protocol-v4 A/B receipt carries the paired materiality evidence."
    )
    print()
    print("## Paths and allocation")
    print()
    print(
        "Allocation counts and bytes are exact per-call censuses in each session; "
        "a range denotes differing observed censuses. Setup time is sampled across "
        "sessions and carries its own interval."
    )
    print()
    print("| Case | selected path | ns/call | interval | sessions | allocations/call | bytes/call | setup ns | setup interval |")
    print("|---|---|---:|---|---:|---:|---:|---:|---|")
    for case in ladder:
        rows = by_case[case]
        median, low, high, _ = order_statistic([row["ns_per_call"] for row in rows])
        allocations = sorted({row["allocations_per_call"] for row in rows})
        allocated = sorted({row["allocated_bytes_per_call"] for row in rows})
        setup, setup_low, setup_high, _ = order_statistic([row["setup_ns"] for row in rows])
        print(
            f"| `{case}` | `{rows[0]['selected_path']}` | {number(median)} | "
            f"[{number(low)}, {number(high)}] | {len(rows)} | {render(allocations)} | "
            f"{render(allocated)} | {number(setup)} | "
            f"[{number(setup_low)}, {number(setup_high)}] |"
        )
    print()

    print("## Scatter share of the BICM channel")
    print()
    print(
        "Each session's direct-scatter wall time divides by that session's "
        "full max-log BICM channel wall time for the same MODCOD. The row gives "
        f"the median of those {len(sessions)} per-session shares and the "
        f"order-statistic interval (coverage {coverage:.3f}). The cases run as separate "
        "processes under the counting allocator, so this share describes "
        "composition; the paired protocol-v4 A/B receipt decides materiality."
    )
    print()
    print("| MODCOD | sessions | share | interval |")
    print("|---|---:|---:|---|")
    for modcod in MODCODS:
        direct = by_case[f"{modcod}-direct"]
        channel = by_case[f"{modcod}-bicm-channel"]
        shares = [
            100.0 * a["ns_per_call"] / b["ns_per_call"]
            for a, b in zip(direct, channel, strict=True)
        ]
        share, low, high, _ = order_statistic(shares)
        print(f"| `{modcod}` | {len(shares)} | {share:.3f}% | [{low:.3f}%, {high:.3f}%] |")
    print()

    print("## Hardware counters and hot instructions")
    print()
    print(
        "The status files record perf-stat counters and sampled hot symbols for each "
        "repetition. Status zero means collection succeeded; a nonzero "
        "status retains stderr as the unavailable outcome. The attribution-table "
        "generator forms across-repetition intervals from these files."
    )
    print()
    print("| Case | repetitions | perf stat success | perf record success | source directories |")
    print("|---|---:|---:|---:|---|")
    for case in ladder:
        statuses = []
        for path in session_paths:
            rep = path.parent
            stat = rep / "counters" / f"{case}.status"
            record = rep / "hot" / f"{case}.status"
            statuses.append(
                (stat.is_file() and stat.read_text().strip() == "0",
                 record.is_file() and record.read_text().strip() == "0")
            )
        print(
            f"| `{case}` | {len(statuses)} | "
            f"{sum(stat for stat, _ in statuses)}/{len(statuses)} | "
            f"{sum(record for _, record in statuses)}/{len(statuses)} | "
            "`rep-NN/counters/`, `rep-NN/hot/` |"
        )


def render(values):
    return str(values[0]) if len(values) == 1 else f"{values[0]}..{values[-1]}"


if __name__ == "__main__":
    main()
