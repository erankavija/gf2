#!/usr/bin/env python3
"""Render the repeated DVB-T2 consumer profile into deterministic Markdown."""

import json
import pathlib
import sys

LOW_RANK, HIGH_RANK = 2, 8
COVERAGE = "0.961"


def interval(values):
    ordered = sorted(values)
    middle = ordered[len(ordered) // 2]
    if len(ordered) >= HIGH_RANK:
        return middle, ordered[LOW_RANK - 1], ordered[HIGH_RANK - 1]
    return middle, ordered[0], ordered[-1]


def number(value):
    if value >= 1000:
        return f"{value:,.0f}".replace(",", " ")
    if value >= 10:
        return f"{value:.1f}"
    return f"{value:.3f}"


def main():
    root = pathlib.Path(sys.argv[1])
    session_paths = sorted(root.glob("rep-*/cases.json"))
    if not session_paths:
        raise SystemExit(f"no completed profile sessions under {root}")
    sessions = [json.loads(path.read_text()) for path in session_paths]
    ladder = [case["id"] for case in json.loads((root / "ladder.json").read_text())]
    by_case = {case: [] for case in ladder}
    for session in sessions:
        for record in session:
            by_case[record["id"]].append(record)

    print("# DVB-T2 interleaver dynamic profile")
    print()
    print("> **Diátaxis Type:** Reference")
    print()
    print(
        f"Generated by `summarize-profile.py` from {len(sessions)} completed session records. "
        f"Each session contributes the median of five 40 ms windows; intervals are the "
        f"order-statistic [x({LOW_RANK}), x({HIGH_RANK})] interval with coverage {COVERAGE} "
        f"when all nine sessions are present. The allocation counter adds relaxed atomics, so "
        "these wall times explain composition only; the protocol-v4 A/B receipt carries the "
        "paired materiality evidence."
    )
    print()
    print("## Paths and allocation")
    print()
    print("| Case | selected path | ns/call | interval | sessions | allocations/call | bytes/call | setup ns |")
    print("|---|---|---:|---|---:|---:|---:|---:|")
    for case in ladder:
        rows = by_case[case]
        median, low, high = interval([row["ns_per_call"] for row in rows])
        allocations = sorted({row["allocations_per_call"] for row in rows})
        allocated = sorted({row["allocated_bytes_per_call"] for row in rows})
        setup, _, _ = interval([row["setup_ns"] for row in rows])
        print(
            f"| `{case}` | `{rows[0]['selected_path']}` | {number(median)} | "
            f"[{number(low)}, {number(high)}] | {len(rows)} | {render(allocations)} | "
            f"{render(allocated)} | {number(setup)} |"
        )
    print()

    print("## Scatter share of the BICM channel")
    print()
    print(
        "The descriptive share divides the direct scatter's across-session median by the "
        "full max-log BICM channel median for the same MODCOD. Separate processes and the "
        "counting allocator mean this quotient has no decision interval."
    )
    print()
    print("| MODCOD | direct ns/call | BICM ns/call | descriptive share |")
    print("|---|---:|---:|---:|")
    for modcod in ("qam16-r12-normal", "qam64-r12-normal", "qam16-r12-short", "qam64-r12-short"):
        direct, _, _ = interval([row["ns_per_call"] for row in by_case[f"{modcod}-direct"]])
        bicm, _, _ = interval([row["ns_per_call"] for row in by_case[f"{modcod}-bicm-channel"]])
        print(f"| `{modcod}` | {number(direct)} | {number(bicm)} | {100.0 * direct / bicm:.3f}% |")
    print()

    print("## Hardware counters and hot instructions")
    print()
    print(
        "Each completed repetition records perf-stat counters, sampled hot symbols, "
        "and an instruction listing. Status zero means collection succeeded; a nonzero "
        "status retains stderr as the unavailable outcome. The attribution-table "
        "generator forms across-repetition intervals from these files."
    )
    print()
    print("| Case | repetitions | perf stat success | perf record success | source directories |")
    print("|---|---:|---:|---:|---|")
    for case in ladder:
        statuses = []
        for path in session_paths:
            rep = path.parent
            stat = rep / "counters" / f"{case}.status"
            record = rep / "hot" / f"{case}.status"
            statuses.append(
                (stat.is_file() and stat.read_text().strip() == "0",
                 record.is_file() and record.read_text().strip() == "0")
            )
        print(
            f"| `{case}` | {len(statuses)} | "
            f"{sum(stat for stat, _ in statuses)}/{len(statuses)} | "
            f"{sum(record for _, record in statuses)}/{len(statuses)} | "
            "`rep-NN/counters/`, `rep-NN/hot/` |"
        )


def render(values):
    return str(values[0]) if len(values) == 1 else f"{values[0]}..{values[-1]}"


if __name__ == "__main__":
    main()
