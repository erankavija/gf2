#!/usr/bin/env python3
"""Project the committed residual-shift profile evidence into tables.

Usage: dev/active/c04dd4ac-zen3-shifts-and-permutations/survey/summarize-shift-receipt.py

Reads only committed artifacts: the accepted receipt and its acceptance
summary, the receipt-local input snapshots, the execution log, the frozen
family addendum, the family ledger, the semantic validation record and the
production-consumer audit. Writes `dev/bench_results/c04dd4ac/residual-shift-tables.md`.
Every value in the output is recomputed or projected from those files, so two
consecutive runs over one committed tree produce the same bytes.

Ratios, intervals, decisions and outcomes come from the acceptance summary that
`benchmark-acceptance` recomputes from the raw paired windows in the receipt.
Per-arm call times, window counts, selected dispatch paths and the execution-log
tallies are descriptive summaries of the same receipt and log; they carry no
confidence interval and decide nothing.
"""

import hashlib
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, os.pardir, os.pardir, os.pardir, os.pardir))
ACTIVE = "dev/active/c04dd4ac-zen3-shifts-and-permutations"
CAMPAIGN = "dev/bench_results/c04dd4ac/residual-shift-profile"
OUTPUT = "dev/bench_results/c04dd4ac/residual-shift-tables.md"
GENERATOR = f"{ACTIVE}/survey/summarize-shift-receipt.py"

ADDENDUM = f"{ACTIVE}/shift-profile-addendum.json"
LEDGER = f"{ACTIVE}/shift-profile-trial-ledger.jsonl"
VALIDATION = f"{ACTIVE}/shift-profile-validation.json"
AUDIT = f"{ACTIVE}/shift-profile-consumer-audit.json"
RECEIPT = f"{CAMPAIGN}/receipt.json"
ACCEPTANCE = f"{CAMPAIGN}/acceptance-summary.json"
EXECUTION_LOG = f"{CAMPAIGN}/execution.log"


def read_bytes(relative):
    with open(os.path.join(ROOT, relative), "rb") as handle:
        return handle.read()


def read_json(relative):
    return json.loads(read_bytes(relative))


def digest(relative):
    return hashlib.sha256(read_bytes(relative)).hexdigest()


def cell(text):
    """Escapes the column separator so a projected value cannot split a row."""
    return text.replace("|", "\\|")


def table(lines, header, rows):
    lines.append("| " + " | ".join(cell(name) for name in header) + " |")
    lines.append("|" + "|".join(["---"] * len(header)) + "|")
    for row in rows:
        lines.append("| " + " | ".join(cell(value) for value in row) + " |")
    lines.append("")


def fmt_interval(interval):
    return "{:.4f} [{:.4f}, {:.4f}]".format(
        interval["estimate"], interval["lower"], interval["upper"]
    )


def relative_half_width(interval):
    estimate = interval["estimate"]
    return max(estimate - interval["lower"], interval["upper"] - estimate) / estimate


def flagged(cell, factor):
    windows = 0
    marked = 0
    for pair in cell["pairs"]:
        for side in ("baseline", "candidate"):
            per_call = [w["elapsed_ns"] / w["calls"] for w in pair[side]["windows"]]
            if not per_call:
                continue
            median = statistics.median(per_call)
            windows += len(per_call)
            marked += sum(1 for value in per_call if value >= factor * median)
    return marked, windows


def preamble(lines, addendum, receipt, acceptance):
    effect = addendum["effect"]
    settings = receipt["settings"]
    lines += [
        "# Residual `BitVec` shift profile evidence tables",
        "",
        "> **Diátaxis Type:** Reference",
        "",
        f"Generated by `{GENERATOR}` from the committed artifacts it names below. "
        f"Nothing here is transcribed by hand.",
        "",
        "Sources and their SHA-256 digests:",
        "",
    ]
    table(
        lines,
        ["Artifact", "SHA-256"],
        [
            [f"`{path}`", f"`{digest(path)}`"]
            for path in (
                ADDENDUM,
                LEDGER,
                VALIDATION,
                AUDIT,
                RECEIPT,
                ACCEPTANCE,
                EXECUTION_LOG,
            )
        ],
    )
    lines += [
        "The ratio is `median(baseline) / median(candidate)` over the pairs of one "
        "cell. The baseline arm is the residual scalar-carry path at the cell's "
        "declared residual offset and the candidate arm is the existing word-aligned "
        "dispatch at offset "
        f"{addendum['cells'][0]['workload']['size']['control_offset']}, so a ratio above "
        "one means the residual path consumes proportionally more time than the "
        "word-aligned control. The two arms run different offsets on purpose: the "
        "control is a workload reference, not a semantically interchangeable "
        "implementation, so no row supports substitution or adoption.",
        "",
        "Intervals are the acceptance tool's whole-pair percentile bootstrap over "
        f"{settings['bootstrap_resamples']} resamples at the per-comparison confidence "
        f"{acceptance['family']['per_comparison_confidence']:.6f} that the family "
        f"accounting below derives. Each cell contributes "
        f"{len(receipt['cells'][0]['pairs'])} counterbalanced pairs and each execution "
        f"contributes {settings['windows_per_execution']} calibrated "
        f"{settings['window_target_ms']} ms windows. Relative half-width is "
        "`max(estimate - lower, upper - estimate) / estimate`.",
        "",
        "The evaluator's improvement margin for every cell is the addendum's "
        f"`effect.material_gap_threshold` of {effect['material_gap_threshold']}, so a "
        "cell decided `improved` is exactly a cell whose interval lower bound reaches "
        "the predeclared material gap, and a cell decided `regressed` is one whose "
        "upper bound lies below the equivalence floor "
        f"1/{effect['equivalence_margin']}, meaning the residual path costs less than "
        "the control. Per-arm call times, window tallies, selected paths and log "
        "counts are descriptive: they carry no interval and decide nothing.",
        "",
    ]


def acceptance_tables(lines, addendum, receipt, acceptance):
    family = acceptance["family"]
    lines += [
        "## Campaign acceptance",
        "",
        f"Source: `{ACCEPTANCE}` over receipt digest "
        f"`{acceptance['receipt_sha256']}`; label **{acceptance['label']}**, verdict "
        f"**{acceptance['verdict']}**, qualifies for production selection "
        f"{str(acceptance['qualifies']).lower()}, findings {len(acceptance['findings'])}, "
        f"sessions {receipt['execution_log']['sessions']}, resumed "
        f"{str(receipt['execution_log']['resumed']).lower()}. Family "
        f"`{family['family_id']}`: {family['comparisons']} comparisons at family-wise "
        f"alpha {family['family_alpha']:g}, per-comparison confidence "
        f"{family['per_comparison_confidence']:.6f}. Protocol version "
        f"{addendum['protocol']['version']}. Toolchain `{receipt['toolchain']}`. "
        f"Campaign seed {receipt['campaign_seed']}. Host `{receipt['host']['hostname']}`, "
        f"`{receipt['host']['cpu_model']}`, kernel `{receipt['host']['os_kernel']}`.",
        "",
    ]
    verdicts = {cell["cell_id"]: cell for cell in acceptance["cells"]}
    factor = receipt["settings"]["flagged_window_factor"]
    rows = []
    for cell in receipt["cells"]:
        verdict = verdicts[cell["cell_id"]]
        interval = verdict["interval"]
        marked, windows = flagged(cell, factor)
        rows.append(
            [
                f"`{cell['cell_id']}`",
                cell["role"],
                cell["status"],
                ",".join(str(cpu) for cpu in cell["resolved_cpus"]),
                str(len(cell["pairs"])),
                f"{marked}/{windows}",
                fmt_interval(interval),
                "{:.4f}".format(relative_half_width(interval)),
                verdict["decision"],
                verdict["outcome"],
            ]
        )
    table(
        lines,
        [
            "Cell",
            "Role",
            "Status",
            "CPUs",
            "Pairs",
            "Flagged windows",
            "Residual/control ratio [interval]",
            "Relative half-width",
            "Decision",
            "Outcome",
        ],
        rows,
    )
    if acceptance["findings"]:
        table(
            lines,
            ["Rule", "Severity", "Cell", "Message"],
            [
                [
                    finding["rule"],
                    finding["severity"],
                    f"`{finding['cell']}`" if finding.get("cell") else "-",
                    finding["message"],
                ]
                for finding in acceptance["findings"]
            ],
        )
    else:
        lines += ["No findings.", ""]
    unresolved = sorted(
        {
            setting
            for cell in acceptance["cells"]
            for setting in cell["unresolved_settings"]
        }
    )
    if unresolved:
        lines += [
            "Every cell records the unresolved settings "
            + ", ".join(f"`{name}`" for name in unresolved)
            + ". The addendum leaves them null because an exploratory family with no "
            "adoptable candidate declares no production speedup rule and no measured "
            "resolution; an unresolved setting keeps every cell in the exploratory "
            "`pilot` outcome and bars production selection.",
            "",
        ]


def workload_table(lines, addendum):
    lines += [
        "## Frozen workload matrix",
        "",
        f"Source: `{ADDENDUM}`, frozen at {addendum['frozen']['frozen_utc']}.",
        "",
    ]
    rows = []
    for cell in addendum["cells"]:
        size = cell["workload"]["size"]
        rows.append(
            [
                f"`{cell['cell_id']}`",
                cell["role"],
                cell["objective"],
                f"{size['length_bits']:,}".replace(",", " "),
                str(size["residual_offset"]),
                str(size["control_offset"]),
                str(cell["workload"]["seed"]),
                cell["cache_state"],
                cell["scaling"],
                cell["metric_kind"],
                str(cell["workers"]["declared"]),
            ]
        )
    table(
        lines,
        [
            "Cell",
            "Role",
            "Objective",
            "Length bits",
            "Residual offset",
            "Control offset",
            "Fixture seed",
            "Cache state",
            "Scaling",
            "Metric kind",
            "Workers",
        ],
        rows,
    )


def arm_table(lines, receipt):
    lines += [
        "## Descriptive per-arm call times",
        "",
        f"Source: `{RECEIPT}`, the per-execution `ns_per_call` of each pair. The "
        "median is over the executions of one side of one cell and the range is their "
        "minimum and maximum; neither carries an interval.",
        "",
    ]
    rows = []
    for cell in receipt["cells"]:
        for side in ("baseline", "candidate"):
            executions = [pair[side] for pair in cell["pairs"]]
            per_call = [execution["ns_per_call"] for execution in executions]
            paths = sorted({execution["selected_path"] for execution in executions})
            workers = sorted({execution["workers_observed"] for execution in executions})
            states = sorted(
                {execution["cache_state_applied"] for execution in executions}
            )
            arm = cell[side + "_arm"]
            rows.append(
                [
                    f"`{cell['cell_id']}`",
                    side,
                    f"`{arm}`",
                    f"`{receipt['arms'][arm]['build']}`",
                    str(len(executions)),
                    "{:.4f}".format(statistics.median(per_call)),
                    "{:.4f}-{:.4f}".format(min(per_call), max(per_call)),
                    ", ".join(f"`{path}`" for path in paths),
                    ", ".join(str(value) for value in workers),
                    ", ".join(states),
                ]
            )
    table(
        lines,
        [
            "Cell",
            "Side",
            "Arm",
            "Build",
            "Executions",
            "Median ns/call",
            "Call range ns",
            "Selected path",
            "Workers observed",
            "Cache state applied",
        ],
        rows,
    )


def disposition_table(lines, addendum, acceptance):
    threshold = addendum["effect"]["material_gap_threshold"]
    lines += [
        "## Materiality disposition under the frozen rule",
        "",
        f"Source: the interval of each cell in `{ACCEPTANCE}` against "
        f"`effect.material_gap_threshold` = {threshold} of `{ADDENDUM}`. A cell is "
        "material when its interval lower bound reaches the threshold, which is the "
        "same test the evaluator applies for the `improved` decision. "
        f"{addendum['effect']['material_gap_rationale']}",
        "",
    ]
    rows = []
    material = []
    for cell in acceptance["cells"]:
        interval = cell["interval"]
        is_material = interval["lower"] >= threshold
        if is_material:
            material.append(cell["cell_id"])
        if interval["upper"] < 1.0:
            position = "residual below control"
        elif is_material:
            position = "at or above the threshold"
        else:
            position = "straddles the threshold"
        rows.append(
            [
                f"`{cell['cell_id']}`",
                "{:.4f}".format(interval["lower"]),
                "{:.4f}".format(interval["estimate"]),
                "{:.4f}".format(interval["upper"]),
                "yes" if is_material else "no",
                position,
                cell["decision"],
            ]
        )
    table(
        lines,
        [
            "Cell",
            "Ratio lower bound",
            "Ratio estimate",
            "Ratio upper bound",
            "Material",
            "Interval position",
            "Decision",
        ],
        rows,
    )
    lines += [
        f"Material cells: {len(material)} of {len(acceptance['cells'])}"
        + (
            ": " + ", ".join(f"`{cell_id}`" for cell_id in material) + "."
            if material
            else "."
        ),
        "",
        "A material cell triggers the addendum's planning-time barrier. It authorizes "
        "no production source: `complexity_budget.max_new_unsafe_kernels` is "
        f"{addendum['complexity_budget']['max_new_unsafe_kernels']} and "
        "`complexity_budget.max_added_source_lines` is "
        f"{addendum['complexity_budget']['max_added_source_lines']} in the same frozen "
        "addendum.",
        "",
    ]


def execution_table(lines, addendum, receipt):
    lines += [
        "## Execution-log integrity",
        "",
        f"Source: `{EXECUTION_LOG}`, pinned by `receipt.execution_log.sha256` = "
        f"`{receipt['execution_log']['sha256']}`, recounted event by event.",
        "",
    ]
    counts = {}
    sessions = set()
    terminal = None
    for line in read_bytes(EXECUTION_LOG).splitlines():
        if not line.strip():
            continue
        record = json.loads(line)
        counts[record["event"]] = counts.get(record["event"], 0) + 1
        sessions.add(record["session_id"])
        terminal = record["event"]
    statuses = sorted({cell["status"] for cell in receipt["cells"]})
    pairs = sorted({len(cell["pairs"]) for cell in receipt["cells"]})
    rows = [
        ["Addendum cells", str(len(addendum["cells"]))],
        ["`cell-start` records", str(counts.get("cell-start", 0))],
        ["`cell-complete` records", str(counts.get("cell-complete", 0))],
        ["`checkpoint-accepted` records", str(counts.get("checkpoint-accepted", 0))],
        ["Receipt cells", str(len(receipt["cells"]))],
        ["Distinct receipt cell statuses", ", ".join(f"`{s}`" for s in statuses)],
        ["Distinct pair counts per cell", ", ".join(str(n) for n in pairs)],
        ["Distinct sessions in the log", str(len(sessions))],
        ["Sessions the receipt records", str(receipt["execution_log"]["sessions"])],
        ["`paused` records", str(counts.get("paused", 0))],
        ["Terminal record", f"`{terminal}`"],
        [
            "Checkpoint manifest digest",
            f"`{receipt['checkpoints']['manifest_sha256']}`",
        ],
    ]
    table(lines, ["Fact", "Value"], rows)
    lines += [
        "The campaign is bounded and resumable: each session measures the cells its "
        "budget allows, checkpoints them, records `paused`, and the next session "
        "records the earlier cells as omitted because they completed in a prior "
        "session. The last session records the terminal event above.",
        "",
    ]


def family_table(lines, addendum, receipt, acceptance):
    lines += [
        "## Family accounting",
        "",
        f"Source: `{LEDGER}`, snapshotted receipt-local as "
        f"`{receipt['trial_ledger']['snapshot']}` and pinned by "
        f"`receipt.trial_ledger.sha256` = `{receipt['trial_ledger']['sha256']}`.",
        "",
    ]
    entries = [
        json.loads(line)
        for line in read_bytes(LEDGER).splitlines()
        if line.strip()
    ]
    table(
        lines,
        [
            "Sequence",
            "Campaign",
            "Predecessor",
            "Addendum SHA-256",
            "Comparisons",
            "Protocol",
            "Candidates",
        ],
        [
            [
                str(entry["sequence"]),
                f"`{entry['campaign']}`",
                f"`{entry['predecessor'][:16]}`",
                f"`{entry['addendum_sha256'][:16]}`",
                str(entry["comparisons"]),
                str(entry["protocol_version"]),
                ", ".join(entry["candidates"]) if entry["candidates"] else "none",
            ]
            for entry in entries
        ],
    )
    confirmatory = [
        cell for cell in addendum["cells"] if cell["role"] != "exploratory"
    ]
    spending = [entry for entry in entries if entry["comparisons"] > 0]
    attempts = max(len(spending), 1)
    family = acceptance["family"]
    alpha = addendum["family_wise"]["alpha"]
    lines += [
        f"The addendum declares {len(confirmatory)} confirmatory or holdout cells, so "
        "the reservation spends "
        f"{entries[-1]['comparisons']} comparisons and names "
        f"{len(entries[-1]['candidates'])} candidate identities. The evaluator derives "
        f"the attempt alpha as `alpha / (t(t+1))` over the {attempts} budget-spending "
        f"attempt in the chain, which is {alpha:g} / "
        f"({attempts} * {attempts + 1}) = {family['family_alpha']:g}, and the "
        f"per-comparison confidence as `1 - alpha_attempt / m` over "
        f"m = {family['comparisons']} comparisons, which is "
        f"{family['per_comparison_confidence']:.6f}. The chain is its own authority: "
        "the first entry's predecessor is the all-zero genesis and every later entry "
        "binds the SHA-256 of the line before it.",
        "",
    ]


def corpus_table(lines):
    validation = read_json(VALIDATION)
    audit = read_json(AUDIT)
    lines += [
        "## Semantic oracle corpus",
        "",
        f"Source: `{VALIDATION}`, the verifier the measured executable runs before the "
        "launcher stages any timing.",
        "",
    ]
    table(
        lines,
        ["Property", "Value"],
        [
            ["Fixture cases", str(validation["fixture_cases"])],
            ["Failures", str(len(validation["failures"]))],
            ["Directions", ", ".join(f"`{d}`" for d in validation["directions"])],
            ["Lengths", ", ".join(str(n) for n in validation["lengths"])],
            ["Base offsets", ", ".join(str(n) for n in validation["base_offsets"])],
            ["Fixture seeds", ", ".join(str(n) for n in validation["seeds"])],
            [
                "Offsets at and beyond the length",
                str(validation["offsets_at_and_beyond_length"]).lower(),
            ],
            [
                "Vector lane crossings",
                str(validation["vector_lane_crossings"]).lower(),
            ],
            [
                "Incomplete final words",
                str(validation["incomplete_final_words"]).lower(),
            ],
            ["In-place aliasing", str(validation["in_place_aliasing"]).lower()],
            ["Zero tail padding", str(validation["zero_tail_padding"]).lower()],
            ["Passed", str(validation["passed"]).lower()],
        ],
    )
    lines += [
        "## Production-consumer audit",
        "",
        f"Source: `{AUDIT}`, recomputed over the repository's production source "
        "closure before the launcher stages any timing.",
        "",
    ]
    table(
        lines,
        ["Property", "Value"],
        [
            ["Scope", audit["scope"]],
            ["Query", f"`{audit['query']}`"],
            ["Owning module excluded", f"`{audit['owner_excluded']}`"],
            ["Files scanned", str(audit["files_scanned"])],
            ["Source closure SHA-256", f"`{audit['source_closure_sha256']}`"],
            [
                "Downstream production calls",
                str(audit["downstream_production_call_count"]),
            ],
            ["Disposition", audit["disposition"]],
            ["Passed", str(audit["passed"]).lower()],
        ],
    )


def main():
    addendum = read_json(ADDENDUM)
    receipt = read_json(RECEIPT)
    acceptance = read_json(ACCEPTANCE)
    lines = []
    preamble(lines, addendum, receipt, acceptance)
    acceptance_tables(lines, addendum, receipt, acceptance)
    workload_table(lines, addendum)
    arm_table(lines, receipt)
    disposition_table(lines, addendum, acceptance)
    execution_table(lines, addendum, receipt)
    family_table(lines, addendum, receipt, acceptance)
    corpus_table(lines)
    with open(os.path.join(ROOT, OUTPUT), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines).rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
