//! `SparseFieldMatrix::matvec` — Criterion benchmarks at every
//! (field, density, size) cell of the `64c88ae4` story matrix's sparse
//! arm, plus the issue `8a90882e` deliverable.
//!
//! Issue `6ed7f050`. Sibling of (the deferred T2 sparse arm of) the
//! reference container harness. Sparse SpMV reference numbers come
//! from a separate harness — fflas-ffpack's sparse interface is via
//! LinBox proper, not fflas-ffpack itself. The gf2 side keeps its own
//! seeded generators here and the cross-library comparison lands when
//! the LinBox harness is added.
//!
//! ## Coverage
//!
//! - **Sizes**: `n ∈ {256, 1024, 4096}`.
//! - **Densities**: `0.01` (1 %), `0.05` (5 %).
//! - **Fields**: `Fp<7>`, `Fp<251>`, `Fp<65521>`, `Fp<2^31-1>`,
//!   `Gf2mWide<1, M=8 AES>`, `Gf2mWide<1, M=16 Conway>`.
//!
//! ## Determinism contract
//!
//! Sparse fixtures consume the same SplitMix64 stream as the dense
//! benches, **but** the support pattern (which `(i, j)` cells are
//! non-zero) is generated by an additional Bernoulli draw per cell from
//! the same stream, *before* the value draw. The fixture is therefore
//! a deterministic function of `(field, density, size)` and the master
//! seed, but it is **not** byte-comparable to a hypothetical fflas /
//! M4RI sparse fixture that uses a different sparsity-sampling scheme.
//! Documented here as the contract a future LinBox harness must match.
//!
//! ## Usage
//!
//! ```bash
//! cargo bench -p gf2-core --bench sparse_spmv --features rand
//! cargo bench -p gf2-core --bench sparse_spmv --features rand -- --test
//! cargo bench -p gf2-core --bench sparse_spmv --features rand -- spmv/Fp_M31/0.01/1024
//! ```

