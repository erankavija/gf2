//! Order factorizations from Brillhart, Lehmer, Selfridge, Tuckerman and
//! Wagstaff, *Factorizations of b^n ± 1*, AMS Contemporary Mathematics 22,
//! third edition (2002), [Cunningham tables 2− and 2+][cunningham].
//!
//! [cunningham]: https://homes.cerias.purdue.edu/~ssw/cun/third/pmain901

use crate::gf2m::Gf2mField_;

/// Decides whether a binary polynomial is primitive over GF(2).
///
/// Bit `i` is the coefficient of `x^i`, including the leading coefficient.
/// All degrees `1..=127` are supported; zero and constant polynomials return
/// `false`. The degree-one polynomial `x + 1` is primitive, and `x` is not.
/// This function does not panic for any `u128` input.
///
/// Uses Rabin's irreducibility criterion (`@/citation/Rabin1980`), then tests
/// the order of `x` against the complete factorization of `2^m - 1` from
/// Brillhart et al., *Factorizations of b^n ± 1*, AMS Contemporary Mathematics
/// 22, third edition (2002), [Cunningham tables 2− and 2+][cunningham].
/// `order_factor_tables_are_complete_and_prime` checks the products and proves
/// primality deterministically, including factors wider than `u64`.
///
/// # Complexity
///
/// For degree `m` and `k` distinct prime factors of `2^m - 1`, O((k + 1)m²)
/// scalar word operations and O(1) auxiliary space; no runtime factorization.
///
/// [cunningham]: https://homes.cerias.purdue.edu/~ssw/cun/third/pmain901
pub fn is_primitive_u128(polynomial: u128) -> bool {
    if polynomial <= 1 || polynomial & 1 == 0 {
        return false;
    }
    let m = 127 - polynomial.leading_zeros();
    if !is_irreducible_u128(polynomial, m) {
        return false;
    }
    let order = (1u128 << m) - 1;
    let factors = ORDER_FACTORS[m as usize];
    x_power_mod(order, m, polynomial) == 1
        && factors.iter().enumerate().all(|(i, &q)| {
            (i > 0 && factors[i - 1] == q) || x_power_mod(order / q, m, polynomial) != 1
        })
}

fn x_power_mod(mut exponent: u128, m: u32, polynomial: u128) -> u128 {
    let mut result = 1;
    let mut base = if m == 1 { polynomial & 1 } else { 2 };
    while exponent != 0 {
        if exponent & 1 != 0 {
            result = Gf2mField_::mul_raw(result, base, m as usize, polynomial);
        }
        exponent >>= 1;
        if exponent != 0 {
            base = Gf2mField_::mul_raw(base, base, m as usize, polynomial);
        }
    }
    result
}

fn gcd_poly_u128(mut a: u128, mut b: u128) -> u128 {
    while b != 0 {
        if a == 0 {
            return b;
        }
        let da = 127 - a.leading_zeros();
        let db = 127 - b.leading_zeros();
        if da < db {
            std::mem::swap(&mut a, &mut b);
        } else {
            a ^= b << (da - db);
        }
    }
    a
}

/// Rabin: x^(2^m) = x and gcd(p, x^(2^(m/q)) - x) = 1 for each prime q | m.
pub(super) fn is_irreducible_u128(polynomial: u128, m: u32) -> bool {
    let x = if m == 1 { polynomial & 1 } else { 2 };
    let mut current = x;
    for i in 1..=m {
        current = Gf2mField_::mul_raw(current, current, m as usize, polynomial);
        // Checking every divisor includes every m/q without factoring m.
        if i <= m / 2 && m.is_multiple_of(i) && gcd_poly_u128(polynomial, current ^ x) != 1 {
            return false;
        }
    }
    current == x
}

