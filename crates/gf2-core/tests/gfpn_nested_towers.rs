//! Integration tests for nested tower extensions: GF(p⁴), GF(p⁶), GF(p¹²).
//!
//! This file complements `gfpn_wide_nested.rs` (which covers the `Wide`
//! accumulator plumbing for GF(p⁴)) by:
//!
//! 1. Running the **canonical field-axiom harness**
//!    ([`gf2_core::field::axiom_tests::test_const_field_axioms`]) over every
//!    nested tower level — the same 1000-cases-per-axiom harness used in the
//!    crate's own unit tests. Exposing that harness to integration tests is
//!    why `gf2-core` now has a `test-support` feature, auto-activated via the
//!    self-dev-dependency so `cargo test` picks it up transparently.
//! 2. Cross-verifying the optimised Karatsuba multiplication against the
//!    shared schoolbook references in
//!    [`common::naive_quadratic_mul`] / [`common::naive_cubic_mul`] for each
//!    nested tower shape.
//! 3. Cross-verifying a handful of hard-coded products, sums, and inverses
//!    against SageMath (vectors generated by
//!    `scripts/sage_vectors_nested_towers.sage`, committed alongside this
//!    file — see that script for the exact commands and the seed used).
//!
//! # Tower chains
//!
//! | GF        | Rust type                                                        | Irreducibles                              |
//! |-----------|------------------------------------------------------------------|-------------------------------------------|
//! | 65537²    | `QuadraticExt<Fp<65537>>`                                        | `u²=3`                                     |
//! | 65537⁴    | `QuadraticExt<QuadraticExt<Fp<65537>>>`                          | `u²=3`, `w²=u`                             |
//! | 7²        | `QuadraticExt<Fp<7>>`                                            | `u²=3`                                     |
//! | 7⁶        | `CubicExt<QuadraticExt<Fp<7>>>`                                  | `u²=3`, `v³=u`                             |
//! | 7¹²       | `QuadraticExt<CubicExt<QuadraticExt<Fp<7>>>>`                    | `u²=3`, `v³=u`, `z²=v+1`                   |
//!
//! Non-residue choices were validated with SageMath by checking that each
//! defining polynomial is irreducible over its base; see the Sage script
//! above for the exact `is_irreducible()` assertions.

