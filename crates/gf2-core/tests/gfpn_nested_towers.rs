// ---------------------------------------------------------------------------
// Axiom harness — focused re-implementation for integration tests.
//
// The full `crate::field::axiom_tests::test_const_field_axioms` is
// `pub(crate)` and unreachable from an integration test. This re-does the
// essential axioms (add/mul/distributivity/inverse roundtrip/hash/Frobenius)
// for each tower level with the requested per-axiom case budget.
// ---------------------------------------------------------------------------

fn compute_hash<T: Hash>(v: &T) -> u64 {
    use std::collections::hash_map::DefaultHasher;
    let mut h = DefaultHasher::new();
    v.hash(&mut h);
    h.finish()
}

/// Run every axiom we care about for the supplied strategy / field. The
/// parameter `p` is the field characteristic (needed for Frobenius + p·x=0).
///
/// The `.clone()` calls below are on `F: Copy` (via `ConstField: Copy`), which
/// clippy flags as unnecessary. We allow them here to keep the harness body
/// structurally identical to the (pub(crate)) `field::axiom_tests` harness,
/// which works for non-`Copy` fields as well — a future refactor that shares
/// code between the two should not have to touch this harness.
#[allow(clippy::clone_on_copy)]
fn run_axioms<F: ConstField + std::fmt::Debug>(
    strategy: BoxedStrategy<F>,
    p: u64,
    cases_per_axiom: u32,
) where
    F::Characteristic: Into<u64>,
{
    let cfg = proptest::test_runner::Config::with_cases(cases_per_axiom);
    let mut runner = proptest::test_runner::TestRunner::new(cfg);

    // (a + b) + c == a + (b + c)
    runner
        .run(
            &(strategy.clone(), strategy.clone(), strategy.clone()),
            |(a, b, c)| {
                let lhs = (a.clone() + b.clone()) + c.clone();
                let rhs = a + (b + c);
                prop_assert_eq!(lhs, rhs);
                Ok(())
            },
        )
        .expect("additive associativity");

    // a + b == b + a
    runner
        .run(&(strategy.clone(), strategy.clone()), |(a, b)| {
            prop_assert_eq!(a.clone() + b.clone(), b + a);
            Ok(())
        })
        .expect("additive commutativity");

    // a + (-a) == 0
    runner
        .run(&strategy, |a| {
            prop_assert!((a.clone() + (-a)).is_zero());
            Ok(())
        })
        .expect("additive inverse");

    // (a * b) * c == a * (b * c)
    runner
        .run(
            &(strategy.clone(), strategy.clone(), strategy.clone()),
            |(a, b, c)| {
                let lhs = (a.clone() * b.clone()) * c.clone();
                let rhs = a * (b * c);
                prop_assert_eq!(lhs, rhs);
                Ok(())
            },
        )
        .expect("multiplicative associativity");

    // a * b == b * a
    runner
        .run(&(strategy.clone(), strategy.clone()), |(a, b)| {
            prop_assert_eq!(a.clone() * b.clone(), b * a);
            Ok(())
        })
        .expect("multiplicative commutativity");

    // a * (b + c) == a*b + a*c
    runner
        .run(
            &(strategy.clone(), strategy.clone(), strategy.clone()),
            |(a, b, c)| {
                let lhs = a.clone() * (b.clone() + c.clone());
                let rhs = (a.clone() * b) + (a * c);
                prop_assert_eq!(lhs, rhs);
                Ok(())
            },
        )
        .expect("distributivity");

    // a * 0 == 0
    runner
        .run(&strategy, |a| {
            prop_assert!((a.clone() * F::zero()).is_zero());
            Ok(())
        })
        .expect("zero annihilation");

    // Non-zero a: a * inv(a) == 1
    runner
        .run(
            &strategy.clone().prop_filter("non-zero", |a| !a.is_zero()),
            |a| {
                let inv = a.inv().expect("non-zero element must have inverse");
                prop_assert!((a * inv).is_one());
                Ok(())
            },
        )
        .expect("inversion roundtrip");

    // Sum of p copies of any element is zero.
    runner
        .run(&strategy, |a| {
            let mut acc = a.zero_like();
            for _ in 0..p {
                acc += a.clone();
            }
            prop_assert!(acc.is_zero());
            Ok(())
        })
        .expect("characteristic p");

    // Equal elements hash equal.
    runner
        .run(&strategy, |a| {
            let b = a.clone();
            prop_assert_eq!(compute_hash(&a), compute_hash(&b));
            Ok(())
        })
        .expect("hash consistency");

    // Frobenius: x^p == frobenius(x, 1).
    runner
        .run(&strategy, |a| {
            let lhs = a.frobenius(1);
            let rhs = a.pow(p);
            prop_assert_eq!(lhs, rhs);
            Ok(())
        })
        .expect("Frobenius vs pow");
}

fn fq2_large_strategy() -> BoxedStrategy<Fq2Large> {
    (0..65537u64, 0..65537u64)
        .prop_map(|(c0, c1)| Fq2Large::new(Fp::new(c0), Fp::new(c1)))
        .boxed()
}

fn fq4_large_strategy() -> BoxedStrategy<Fq4Large> {
    (0..65537u64, 0..65537u64, 0..65537u64, 0..65537u64)
        .prop_map(|(c00, c01, c10, c11)| {
            Fq4Large::new(
                Fq2Large::new(Fp::new(c00), Fp::new(c01)),
                Fq2Large::new(Fp::new(c10), Fp::new(c11)),
            )
        })
        .boxed()
}

fn fq6_strategy() -> BoxedStrategy<Fq6> {
    proptest::array::uniform6(0u64..7)
        .prop_map(fq6_from_flat)
        .boxed()
}

fn fq12_strategy() -> BoxedStrategy<Fq12> {
    proptest::array::uniform12(0u64..7)
        .prop_map(fq12_from_flat)
        .boxed()
}

