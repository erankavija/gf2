#[test]
fn sage_cross_verify_fq4() {
    for (i, v) in SAGE_FQ4.iter().enumerate() {
        let a = fq4_from_flat(v.a);
        let b = fq4_from_flat(v.b);
        assert_eq!(fq4_to_flat(a * b), v.prod, "Fq4 prod mismatch at {i}");
        assert_eq!(fq4_to_flat(a + b), v.sum, "Fq4 sum mismatch at {i}");
        let inv = a.inv().expect("Sage-generated a is non-zero");
        assert_eq!(fq4_to_flat(inv), v.inv_a, "Fq4 inv mismatch at {i}");
    }
}

