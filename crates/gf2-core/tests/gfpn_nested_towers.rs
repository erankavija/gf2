//! Integration tests for nested tower extensions: GF(p⁴), GF(p⁶), GF(p¹²).
//!
//! This file complements `gfpn_wide_nested.rs` (which already covers the `Wide`
//! accumulator plumbing for GF(p⁴)) by:
//!
//! 1. Running focused field-axiom checks (add/mul/distributivity + inverse
//!    roundtrip + hash stability + Frobenius consistency) over all three
//!    chains via proptest.
//! 2. Cross-verifying the optimised Karatsuba multiplication against a
//!    fresh, independent schoolbook implementation for each tower shape.
//!    The naive routines here take deliberately different coordinate-
//!    mixing shapes from those in `karatsuba_cross_verify.rs` so no helper
//!    is shared with the Karatsuba code path or a common reference.
//! 3. Cross-verifying a handful of hard-coded products, sums, and inverses
//!    against SageMath (vectors generated with Sage 10.8 using the
//!    regenerator script documented below).
//!
//! # Tower chains
//!
//! | GF        | Rust type                                                        | Irreducibles                              |
//! |-----------|------------------------------------------------------------------|-------------------------------------------|
//! | 65537²    | `Fp<65537>`                                                      | base                                       |
//! | 65537⁴    | `QuadraticExt<QuadraticExt<Fp<65537>>>`                          | `u²=3`, `w²=u`                             |
//! | 7²        | `QuadraticExt<Fp<7>>`                                            | `u²=3`                                     |
//! | 7⁶        | `CubicExt<QuadraticExt<Fp<7>>>`                                  | `u²=3`, `v³=u`                             |
//! | 7¹²       | `QuadraticExt<CubicExt<QuadraticExt<Fp<7>>>>`                    | `u²=3`, `v³=u`, `z²=v+1`                   |
//!
//! Non-residue choices were validated with SageMath by checking that each
//! defining polynomial is irreducible over its base. Sage notes:
//!
//! * GF(7²): `x² − 3` irreducible iff `3` is a QR-non-residue mod 7 — yes
//!   (Legendre `(3/7) = −1`).
//! * GF(7⁶): `x³ − u` irreducible over GF(7²) — yes (Sage `.is_irreducible()`
//!   returned `True`; `u` is a cubic non-residue in GF(7²)).
//! * GF(7¹²): `x² − (v + 1)` irreducible over GF(7⁶) — yes, confirmed via
//!   Sage; `v + 1` is a quadratic non-residue in GF(7⁶).
//! * GF(65537⁴): `x² − u` irreducible over GF(65537²) (same construction as
//!   in `gfpn_wide_nested.rs`, reused here for the Sage cross-verify).
//!
//! # SageMath cross-verification
//!
//! SageMath was available on the build host at the time this test was
//! written. Test vectors were generated by the Sage script embedded below
//! and hard-coded as the `SAGE_*` arrays. To regenerate (for example if a
//! tower definition changes) run:
//!
//! ```bash
//! sage -c "$(cat <<'PY'
//! from random import Random
//! rng = Random(int(42))
//! p = 65537
//! Fp = GF(p); R.<x> = PolynomialRing(Fp)
//! Fq2.<u> = Fp.extension(x^2 - 3)
//! R4.<y> = PolynomialRing(Fq2); Fq4.<w> = Fq2.extension(y^2 - u)
//! # ... (see the full script in scripts/sage_vectors_nested_towers.sage or
//! #      recover from the task description of jit issue 86b3dc7d).
//! PY
//! )"
//! ```
//!
//! If SageMath becomes unavailable (e.g., on a CI host without a Sage
//! install), the Sage cross-verify tests still build and run — the vectors
//! are static constants — but regeneration would need Sage reinstalled.
//! **At the time of writing, `which sage` returned `/usr/bin/sage`
//! (version 10.8), so the criterion is satisfied.**

